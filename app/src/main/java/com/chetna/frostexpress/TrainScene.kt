                    Color(0xFFFFE49A).copy(alpha = a), Offset(-4f * u, (top - 4f) * u), Size((CAR_W + 8f) * u, (CAR_H + 8f) * u),
                    CornerRadius(14f * u, 14f * u), style = Stroke(5f * u),
                )
            }
        }
        spriteXScale = 1f
    }
    if (dark > 0.01f) {
        val trainH = npc.trainLen * u * z
        // the whole interior is lit evenly: a little dimmer and a little warmer, no bright hot spots
        drawRect(Color(0xFF0B1B3A).copy(alpha = dark * 0.5f), Offset(originX, ny), Size(trainPx, trainH))
        drawRect(Color(0xFFFFB866).copy(alpha = dark * 0.12f), Offset(originX, ny), Size(trainPx, trainH), blendMode = BlendMode.Plus)
        val cx = originX + trainPx / 2f
        val beam = Path().apply {
            moveTo(cx - 40f * u * z, ny + 4f * u * z); lineTo(cx + 40f * u * z, ny + 4f * u * z)
            lineTo(cx + 110f * u * z, ny - 190f * u * z); lineTo(cx - 110f * u * z, ny - 190f * u * z); close()
        }
        drawPath(beam, Brush.verticalGradient(listOf(Color.Transparent, Color(0xFFFFF3B0).copy(alpha = dark * 1.4f)), startY = ny - 190f * u * z, endY = ny))
    }
    if (fx && sceneGfx >= 2 && w > 4f && h > 4f) safeFx { drawPostFx(w, h, dark, storm) }
    if (npc.trainLen > npc.viewH + 1f) { // scroll bar: the train is taller than the screen
        val frac = npc.viewH / npc.trainLen
        val barH = h * frac
        val barY = (h * (npc.camY / npc.trainLen)).coerceIn(0f, h - barH)
        drawRoundRect(Color(0x55203040), Offset(w - 7f * u, barY), Size(4f * u, barH), CornerRadius(2f * u, 2f * u))
    }
    if (boosting || shopTurbo) drawSpeedLines(time, originX, trainPx, w, h, u)

}

