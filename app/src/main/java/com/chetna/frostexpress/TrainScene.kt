        }
        dot(Color(0xFF8A949E), 62f, wy, 2f)
        for (k in 0 until 3) {
            val t = (time * 0.5f + k / 3f) % 1f
            dot(Color(0xFFFFB347).copy(alpha = (1f - t) * 0.3f), 20f + k * 14f, top + 30f - t * 16f, 5f + t * 4f)
