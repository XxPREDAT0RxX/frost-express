/** A passenger coach. Eight seats in every style; the fit-out depends on the train tier. */
private fun DrawScope.drawSeatingCar(top: Float, car: Int, cars: Int) {
    val baseIdx = (car - 1) * Balance.SEATS_PER_CAR
    val door = top - 6f
    val style = interiorStyle(sceneTier)
    val cols = floatArrayOf(34f, 64f, 126f, 156f)
    val rows = floatArrayOf(top + 24f, top + 62f)
    when (style) {
        2 -> { // commuter: benches along both walls, a standing area and grab poles
            val x0 = 10f
            val x1 = CAR_W - 26f
            for (bx in floatArrayOf(x0, x1)) {
                box(Color(0xFF3E4A57), bx, top + 10f, 16f, CAR_H - 36f, 5f)
                box(Color(0xFF5C83A6), bx + 1.5f, top + 11.5f, 13f, CAR_H - 39f, 4f)
            }
            val ys = floatArrayOf(top + 24f, top + 41f, top + 58f, top + 75f)
            var seat = 0
            for (side in 0..1) for (k in 0 until 4) {
                drawTrainSeat(if (side == 0) x0 + 8f else x1 + 8f, ys[k], sceneRoster.getOrNull(baseIdx + seat), door, 1)
                seat++
            }
            for (k in 0 until 2) {
                val py = top + 36f + k * 44f
                line(Color(0xFFB7BEC6), AISLE_X, py - 14f, AISLE_X, py + 14f, 2f)
                dot(Color(0xFFD7DCE2), AISLE_X, py, 2.6f)
            }
            line(Color(0xFFB7BEC6), 40f, top + 14f, CAR_W - 40f, top + 14f, 1.6f)
        }
        else -> {
            if (style == 4) { // luxury lounge: a rug under the armchairs
                box(Color(0xFFB9605C), 12f, top + 10f, CAR_W - 24f, CAR_H - 36f, 8f)
                box(Color(0xFFD98B7E), 16f, top + 14f, CAR_W - 32f, CAR_H - 44f, 6f)
            } else drawAisle(top, CAR_H - 32f)
            var seat = 0
            for (r in 0 until 2) for (c in 0 until 4) {
                if (style == 1 && c % 2 == 0) { // saloon: a table with a lamp between each pair
                    box(Color(0xFF8A6A4A), cols[c] + 15f - 9f, rows[r] - 7f, 18f, 14f, 3f)
                    box(Color(0xFFD7B98E), cols[c] + 15f - 8f, rows[r] - 6f, 16f, 12f, 2.5f)
                    dot(Color(0xFFFFE9A8), cols[c] + 15f, rows[r] - 1f, 2f)
                }
                if (style == 4 && (c == 1 || c == 3)) { // lounge: a small side table beside the armchair
                    val tx = if (c == 1) cols[c] + 18f else cols[c] - 18f
                    dot(Color(0xFF6B4A3A), tx, rows[r] + 9f, 5.5f)
                    dot(Color(0xFFD7B98E), tx, rows[r] + 9f, 4.2f)
                    dot(Color(0xFFFFE9A8), tx, rows[r] + 9f, 1.8f)
                }
                drawTrainSeat(cols[c], rows[r], sceneRoster.getOrNull(baseIdx + seat), door, if (style == 4) 2 else 0)
                seat++
            }
            if (style == 3) { // sleeper cabins: walls with sliding glass doors onto the corridor, and a partition between the cabins
                val wall = Color(0xFF8A6A4A)
                for (side in 0..1) {
                    val wx = if (side == 0) AISLE_X - 17f else AISLE_X + 14f
                    box(wall, wx, top + 8f, 3f, CAR_H - 32f, 1.5f)
                    for (r in 0 until 2) box(Color(0xFFBFE0F0).copy(alpha = 0.75f), wx - 0.5f, rows[r] - 8f, 4f, 16f, 1f)
                    box(wall, if (side == 0) 8f else AISLE_X + 14f, top + 43f, AISLE_X - 22f, 2.6f, 1f)
                }
            }
        }
    }
    drawToilet(top)
}

