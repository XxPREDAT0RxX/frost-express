"""Puts the Blender window-view renders (blender/window.py, release blender-N window_frames.zip) into the game.

    python3 store_assets/make_window_sprites.py <unzipped window folder>

Writes app/src/main/res/drawable-nodpi/win_cabin.webp, win_<land>_{far,mid,near}.webp, win_cloud1..4.webp and
WindowAtlas.kt with each land's ground colour (the colour at the foot of its near hills), so the ground band
below the hills joins them without a seam. The bottom of each far strip fades out into that colour.
"""
import os, sys
import numpy as np
from PIL import Image

SRC = sys.argv[1]
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, 'app/src/main/res/drawable-nodpi')
KT = os.path.join(ROOT, 'app/src/main/java/com/chetna/frostexpress/WindowAtlas.kt')
LANDS = ['meadow', 'pine', 'savanna', 'desert', 'rainforest', 'snow', 'village']

def save(im, name, q=90):
    im.save(os.path.join(RES, 'win_%s.webp' % name), 'WEBP', quality=q, method=6, alpha_quality=100)

save(Image.open(os.path.join(SRC, 'cabin.png')).convert('RGBA'), 'cabin', 88)
for n in range(1, 5):
    im = Image.open(os.path.join(SRC, 'cloud%d.png' % n)).convert('RGBA')
    save(im.crop(im.getbbox()), 'cloud%d' % n)
grounds = []
for land in LANDS:
    far = np.array(Image.open(os.path.join(SRC, land + '_far.png')).convert('RGBA')).astype(np.float32)
    h = far.shape[0]
    band = far[int(h * 0.9):int(h * 0.97)]
    col = band[..., :3][band[..., 3] > 200].mean(axis=0)
    grounds.append(col)
    fade0 = int(h * 0.82)
    for y in range(fade0, h):   # melt the foot of the hills into the ground colour
        t = (y - fade0) / (h - fade0)
        far[y, :, :3] = far[y, :, :3] * (1 - t) + col * t
    save(Image.fromarray(far.clip(0, 255).astype(np.uint8)), land + '_far')
    for layer in ('mid', 'near'):
        im = Image.open(os.path.join(SRC, '%s_%s.png' % (land, layer))).convert('RGBA')
        save(im, '%s_%s' % (land, layer))
with open(KT, 'w') as f:
    f.write('package com.chetna.frostexpress\n\n// Generated by store_assets/make_window_sprites.py. Do not edit by hand.\n\n')
    f.write('/** The window view\'s lands, in ZONES order, and the ground colour at the foot of each one\'s hills. */\n')
    f.write('object WindowAtlas {\n    val LANDS = listOf(%s)\n' % ', '.join('"%s"' % l for l in LANDS))
    f.write('    val GROUND = longArrayOf(%s)\n}\n' % ', '.join('0xFF%02X%02X%02X' % tuple(int(round(c)) for c in g) for g in grounds))
print('ok')
