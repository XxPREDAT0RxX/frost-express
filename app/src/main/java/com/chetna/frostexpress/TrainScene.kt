    }
    if (look.food > 0) {
        furniture(sp.kitchen, 128f, top + 8f, 54f, 66f)
        val cooking = act == Act.COOK
        if (cooking) glow(138f, top + 30f, 30f, Color(0xFFFF8A2B), 0.5f)
