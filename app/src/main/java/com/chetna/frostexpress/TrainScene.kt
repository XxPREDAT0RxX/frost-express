// Roadside scenery that scrolls past. Kinds: 0 pine, 1 large pine, 2 rock, 3 shrub, 4 snow drift.
// Sorted so ground details are drawn first and trees last (on top).
private val DECOR = List(36) { i ->
    val kind = when (i % 9) { 0, 1, 2 -> 0; 3 -> 1; 4 -> 2; 5 -> 3; 6, 7 -> 4; else -> 0 }
    val r = when (kind) { 0 -> 9f + (i * 5) % 7; 1 -> 17f + (i * 3) % 6; 2 -> 6f + (i * 3) % 5; 3 -> 6f + (i * 7) % 4; else -> 14f + (i * 5) % 12 }
    Decor(i % 2, (i * 0.381966f + 0.07f) % 1f, (i * 37.7f) % DECOR_PERIOD, r, kind)
}.sortedBy { if (it.kind == 4) 0 else if (it.kind == 2 || it.kind == 3) 1 else 2 }

private class Hotspot(val x: Float, val y: Float, val w: Float, val h: Float, val type: UpgradeType)

/** Tappable devices in train space. The first match wins, so specific devices come before whole cars. */
private fun hotspotAt(tx: Float, ty: Float, cars: Int): UpgradeType? {
    val list = ArrayList<Hotspot>()
    val e = NOSE                 // engine car top
    val u = NOSE + PITCH         // utility car top
    list.add(Hotspot(14f, 0f, 162f, NOSE, UpgradeType.PLOW))
    list.add(Hotspot(156f, e + 80f, 28f, 30f, UpgradeType.BOOSTER))
    list.add(Hotspot(8f, e + 8f, 66f, 58f, UpgradeType.ENGINE))
    list.add(Hotspot(118f, e + 80f, 38f, 30f, UpgradeType.ENGINE))
    list.add(Hotspot(126f, e + 8f, 58f, 44f, UpgradeType.COAL))
    list.add(Hotspot(6f, e + 78f, 54f, 32f, UpgradeType.CONDUCTOR))
    list.add(Hotspot(6f, u + 6f, 68f, 58f, UpgradeType.HEAT))
    list.add(Hotspot(126f, u + 6f, 58f, 70f, UpgradeType.FOOD))
    list.add(Hotspot(6f, u + 74f, 66f, 36f, UpgradeType.FOOD))
    list.add(Hotspot(116f, u + 76f, 68f, 34f, UpgradeType.WAGON))
    list.add(Hotspot(AISLE_X - 17f, u + 6f, 34f, 34f, CAR_DEFS[1][3]))
    list.add(Hotspot(AISLE_X - 17f, u + 74f, 34f, 34f, CAR_DEFS[1][4]))
    for (c in 2 until min(cars, CAR_DEFS.size)) {
        val top = NOSE + c * PITCH
        val d = CAR_DEFS[c]
        list.add(Hotspot(AISLE_X - 17f, top + 6f, 34f, 34f, d[4]))
        for (k in 0 until 4) {
            list.add(Hotspot(if (k % 2 == 0) 8f else 114f, top + (if (k < 2) 8f else 62f), 68f, 46f, d[k]))
        }
    }
    return list.firstOrNull { tx >= it.x && tx <= it.x + it.w && ty >= it.y && ty <= it.y + it.h }?.type
}

private fun carY(car: Int, localY: Float): Float = NOSE + car * PITCH + localY

/** The worker visits every installed station in turn. Positions are car-local, converted by carY. */
private fun buildCycle(heat: Boolean, food: Boolean, bed: Boolean, wagon: Boolean, cars: Int): List<Step> {
    val s = ArrayList<Step>()
    s.add(Step(112f, carY(0, 28f), 1f, 0f, Act.SHOVEL_PICK, 1.0f))
    s.add(Step(88f, carY(0, 34f), -1f, 0f, Act.SHOVEL_DROP, 1.1f))
    s.add(Step(112f, carY(0, 28f), 1f, 0f, Act.SHOVEL_PICK, 1.0f))
    s.add(Step(88f, carY(0, 34f), -1f, 0f, Act.SHOVEL_DROP, 1.1f))
    s.add(Step(112f, carY(0, 94f), 1f, 0f, Act.DRIVE, 2.2f))
    if (heat) s.add(Step(74f, carY(1, 34f), -1f, 0f, Act.TURN_VALVE, 2.4f))
    if (food) {
        s.add(Step(124f, carY(1, 30f), 1f, 0f, Act.COOK, 2.6f))
        s.add(Step(76f, carY(1, 92f), -1f, 0f, Act.EAT, 2.4f))
    }
    if (wagon) {
        s.add(Step(86f, carY(1, 96f), -1f, 0f, Act.CRATE_PICK, 1.0f))
        s.add(Step(104f, carY(1, 94f), 1f, 0f, Act.CRATE_PLACE, 1.1f))
    }
    // check on the devices in every extra car
    for (c in 2 until cars) s.add(Step(AISLE_X, carY(c, 56f), if (c % 2 == 0) -1f else 1f, 0f, Act.TURN_VALVE, 1.3f))
    if (bed) s.add(Step(68f, carY(0, 94f), -1f, 0f, Act.SLEEP, 2.4f))
    return s
}

/** Animation-only state for the worker (not part of the game rules). */
private class Npc {
    var x = AISLE_X
    var y = NOSE + 70f
    var faceDeg = 0f
    var phase = 0f
    var actT = 0f
    var camY = 0f
    var zoom = 1f
    var originXpx = 0f      // set while drawing; used to turn taps into train-space positions
    var centerOffDp = 0f
    var cars = 2
    var manualCam = 0f      // camera position while the player scrolls by hand
    var manualLeft = 0f     // seconds left before the camera follows the worker again
    var viewH = 600f // visible height in train-space dp, set from the canvas every frame
    var trainLen = NOSE + 2 * PITCH
    /** Hand scrolling can bring the first or the last car all the way to the middle of the screen. */
    val camLo: Float get() = NOSE + CAR_H / 2f - viewH / 2f
    val camHi: Float get() = max(camLo, trainLen - CAR_H / 2f - viewH / 2f)
    /** Automatic camera: a short train sits in the middle; a long one follows the worker. */
    private val autoLo: Float get() = if (trainLen <= viewH) (trainLen - viewH) / 2f else -60f
    private val autoHi: Float get() = if (trainLen <= viewH) autoLo else trainLen - viewH + 30f
    var working = false
    var cycle: List<Step> = emptyList()
    var idx = 0
    var sig = Int.MIN_VALUE
    var startOffset = 0 // lets a second worker begin halfway through the routine
    private val path = ArrayList<Offset>()

    val step: Step? get() = if (cycle.isEmpty()) null else cycle[idx % cycle.size]
    val act: Act get() = if (working) (step?.act ?: Act.WALK) else Act.WALK
    val carIdx: Int get() = max(0, ((y - NOSE) / PITCH).toInt())

    val carrying: Boolean
        get() {
            val st = step ?: return false
            return st.act == Act.CRATE_PLACE && (!working || actT < st.dur * 0.5f)
        }

    val holdingCoal: Boolean
        get() {
            val st = step ?: return false
            return st.act == Act.SHOVEL_DROP && (!working || actT < st.dur * 0.6f)
        }

    fun sync(heat: Boolean, food: Boolean, bed: Boolean, wagon: Boolean, cars: Int) {
        val s = (if (heat) 1 else 0) + (if (food) 2 else 0) + (if (bed) 4 else 0) + (if (wagon) 8 else 0) + cars * 16
        if (s == sig) return
        sig = s
        cycle = buildCycle(heat, food, bed, wagon, cars)
        this.cars = cars
        trainLen = NOSE + cars * PITCH - GAP + 10f
        if (y > trainLen - 20f) y = trainLen - 20f
        // startOffset -1 = begin halfway through the routine, so two workers never move in lockstep
        idx = if (cycle.isEmpty() || startOffset == 0) 0 else (if (startOffset < 0) cycle.size / 2 else startOffset % cycle.size)
        if (startOffset != 0) cycle.getOrNull(idx)?.let { x = it.x; y = it.y }
        plan()
    }

    private fun plan() {
        path.clear()
        working = false
        actT = 0f
        val t = step ?: return
        if (abs(x - AISLE_X) > 1f) path.add(Offset(AISLE_X, y))
        if (abs(y - t.y) > 1f) path.add(Offset(AISLE_X, t.y))
        path.add(Offset(t.x, t.y))
    }

    private fun turnTo(target: Float, d: Float) {
        var diff = (target - faceDeg) % 360f
        if (diff > 180f) diff -= 360f
        if (diff < -180f) diff += 360f
        faceDeg += diff * min(1f, d * 12f)
    }

    fun update(dt: Float, tempo: Float) {
        val st = step ?: return
        val d = dt * tempo
        if (!working && path.isNotEmpty()) {
            val tgt = path[0]
            val dx = tgt.x - x
            val dy = tgt.y - y
            val dist = sqrt(dx * dx + dy * dy)
            val stride = 64f * d
            if (dist <= stride) {
                x = tgt.x
                y = tgt.y
                path.removeAt(0)
            } else {
                x += dx / dist * stride
                y += dy / dist * stride
            }
            if (dist > 0.01f) turnTo(atan2(dx, -dy) * 57.29578f, d)
            phase += d * 9f
            if (path.isEmpty()) {
                working = true
                actT = 0f
            }
        } else if (working) {
            turnTo(atan2(st.fx, -st.fy) * 57.29578f, d)
            actT += d
            phase += d * 6f
            if (actT >= st.dur) {
                idx = (idx + 1) % cycle.size
                plan()
            }
        }
        if (manualLeft > 0f) {
            manualLeft -= dt
            camY += (manualCam - camY) * min(1f, dt * 12f)
        } else {
            val target = (y - viewH / 2f).coerceIn(autoLo, autoHi)
            camY += (target - camY) * min(1f, dt * 3f)
        }
    }
}

@Composable
fun TrainScene(vm: GameViewModel, modifier: Modifier = Modifier, onDeviceTap: (UpgradeType) -> Unit = {}) {
    val npc = remember { Npc() }
    val npc2 = remember { Npc().also { it.startOffset = -1 } }
    val stations = remember { ArrayList<Station>() }
    val halfH = remember { floatArrayOf(300f) }
    val stopFactor = remember { floatArrayOf(1f) }
    val shelterDwell = remember { floatArrayOf(-1f) }
    var seenStations by remember { mutableIntStateOf(vm.stationSerial) }
    var seenStorms by remember { mutableIntStateOf(vm.stormStationSerial) }
    var time by remember { mutableFloatStateOf(0f) }
    var scroll by remember { mutableFloatStateOf(0f) }

    LaunchedEffect(Unit) {
        var last = 0L
        var acc = 0f
        while (true) {
            withFrameNanos { now ->
                if (last != 0L) acc += (now - last) / 1e9f
                // Frame-rate cap from Settings: only update and redraw once enough time has passed.
                if (last != 0L && acc >= 1f / vm.fpsCap - 0.002f) {
                    val dt = acc.coerceAtMost(0.05f)
                    acc = 0f
                    val boosting = vm.isBoosting
                    time += dt
                    while (seenStations < vm.stationSerial) { seenStations++; stations.add(Station(-110f)) }
                    while (seenStorms < vm.stormStationSerial) { seenStorms++; stations.add(Station(-260f, stop = true)) }
                    // Storm shelter: slow down, stand at the station for a while, then pull away.
                    var factor = 1f
                    val shelter = stations.firstOrNull { it.stop && !it.done }
                    if (shelter != null) {
                        val dist = halfH[0] - shelter.y
                        if (!shelter.paid && dist > 0f) {
                            factor = (dist / 170f).coerceIn(0.07f, 1f)
                        } else {
                            if (!shelter.paid) { shelter.paid = true; vm.collectStation(shelter = true) }
                            shelter.dwell += dt
                            val wait = Balance.STATION_STOP_SEC.toFloat()
                            factor = if (shelter.dwell < wait) 0f else ((shelter.dwell - wait) / 2.5f).coerceIn(0f, 1f)
                            if (factor >= 1f) shelter.done = true
                        }
                    }
                    vm.setMoveFactor(factor)
                    stopFactor[0] = factor
                    shelterDwell[0] = shelter?.takeIf { it.paid && !it.done }?.dwell ?: -1f
                    val ds = (40f + 26f * sqrt(vm.travelSpeed.toFloat())) * (if (boosting) 1.6f else 1f) * dt * factor
                    scroll += ds
                    for (st in stations) {
                        st.y += ds
                        if (!st.stop && !st.paid && st.y >= halfH[0]) { st.paid = true; vm.collectStation() }
                    }
                    stations.removeAll { it.y > halfH[0] * 2f + 260f }
                    npc.sync(
                        heat = vm.level(UpgradeType.HEAT) > 0,
                        food = vm.level(UpgradeType.FOOD) > 0,
                        bed = vm.level(UpgradeType.CONDUCTOR) > 0,
                        wagon = vm.level(UpgradeType.WAGON) > 0,
                        cars = carCount(vm),
                    )
                    npc.update(dt, if (boosting) 1.8f else 1f)
                    if (vm.permLevel(PermType.CREW) > 0) {
                        npc2.sync(
                            heat = vm.level(UpgradeType.HEAT) > 0,
                            food = vm.level(UpgradeType.FOOD) > 0,
                            bed = vm.level(UpgradeType.CONDUCTOR) > 0,
                            wagon = vm.level(UpgradeType.WAGON) > 0,
                            cars = carCount(vm),
                        )
                        npc2.update(dt, if (boosting) 1.8f else 1f)
                    }
                }
                last = now
            }
        }
    }

    val art = rememberSceneArt()
    val mats = rememberMaterials()
    val sprites = rememberGameSprites()
    val base = TIERS[vm.tierIndex]
    val lv = LIVERIES[vm.liveryIndex.coerceIn(0, LIVERIES.lastIndex)]
    val tier = if (vm.liveryIndex > 0 && vm.liveryUnlocked(vm.liveryIndex)) TrainTier(base.name, lv.body, lv.accent) else base
    Canvas(
        modifier.pointerInput(Unit) {
            // Tap a device on the train to open its upgrade.
            detectTapGestures { pos ->
                val u = density
                val tx = (pos.x - npc.originXpx) / (u * npc.zoom)
                val ty = pos.y / (u * npc.zoom) - (npc.centerOffDp - npc.camY)
                hotspotAt(tx, ty, npc.cars)?.let(onDeviceTap)
            }
        }.pointerInput(Unit) {
            // Drag up or down to look along a long train. The camera follows the worker again after 5 s.
            detectVerticalDragGestures(
                onDragStart = { npc.manualCam = npc.camY },
                onVerticalDrag = { change, dy ->
                    change.consume()
                    if (npc.camHi > npc.camLo) {
                        npc.manualCam = (npc.manualCam - dy / (density * npc.zoom)).coerceIn(npc.camLo, npc.camHi)
                        npc.manualLeft = 5f
                    }
                },
            )
        }
    ) {
        val look = Look(
            heat = vm.level(UpgradeType.HEAT),
            food = vm.level(UpgradeType.FOOD),
            coal = vm.level(UpgradeType.COAL),
            booster = vm.level(UpgradeType.BOOSTER),
            conductor = vm.level(UpgradeType.CONDUCTOR),
            plow = vm.level(UpgradeType.PLOW),
            cars = carCount(vm),
            wagon = vm.level(UpgradeType.WAGON),
            lv = IntArray(UpgradeType.values().size) { vm.levels.getOrElse(it) { 0 } },
        )
        halfH[0] = size.height / density / 2f
        sceneArt = art
        sceneMats = mats
        sceneSprites = sprites
        drawScene(npc, if (vm.permLevel(PermType.CREW) > 0) npc2 else null, time, scroll, tier, look, vm.isBoosting, vm.event == GameEvent.AURORA, vm.stormLevel, vm.darkness, stations, vm.postFx)
    }
}

// ---------------------------------------------------------------------------------------------
// Drawing helpers (everything takes dp and converts with the screen density)
// ---------------------------------------------------------------------------------------------
private fun DrawScope.box(color: Color, x: Float, y: Float, w: Float, h: Float, r: Float = 0f) {
    val u = density
    if (r > 0f) {
        drawRoundRect(color, Offset(x * u, y * u), Size(w * u, h * u), CornerRadius(r * u, r * u))
    } else {
        drawRect(color, Offset(x * u, y * u), Size(w * u, h * u))
    }
}

private fun DrawScope.dot(color: Color, x: Float, y: Float, r: Float) {
    drawCircle(color, r * density, Offset(x * density, y * density))
}

private fun DrawScope.line(color: Color, x1: Float, y1: Float, x2: Float, y2: Float, w: Float) {
    val u = density
    drawLine(color, Offset(x1 * u, y1 * u), Offset(x2 * u, y2 * u), w * u)
}

/** Dashed outline that marks an empty slot where an upgrade will be installed. */
private fun DrawScope.slot(x: Float, y: Float, w: Float, h: Float) {
    val u = density
    drawRoundRect(
        Color(0x668A949E),
        Offset(x * u, y * u),
        Size(w * u, h * u),
        CornerRadius(6f * u, 6f * u),
        style = Stroke(width = 2f * u, pathEffect = PathEffect.dashPathEffect(floatArrayOf(8f * u, 6f * u), 0f)),
    )
}

private fun DrawScope.drawScene(
    npc: Npc, npc2: Npc?, time: Float, scroll: Float, tier: TrainTier, look: Look,
    boosting: Boolean, aurora: Boolean, storm: Float, dark: Float, stations: List<Station>, fx: Boolean,
) {
    val u = density
    val w = size.width
    val h = size.height
    val z = (w / u * 0.50f / CAR_W).coerceIn(0.8f, 1.5f)
    npc.viewH = h / u / z
    npc.zoom = z
    fxOn = fx
    fxDark = dark
    val trainPx = CAR_W * u * z
    val originX = (w - trainPx) / 2f
    val centerOff = 0f
    npc.originXpx = originX
    npc.centerOffDp = centerOff
    val art = sceneArt
    if (art != null) {
        // painted snow that scrolls with the ground (256 dp tile)
        val tile = 256f
        texRect(art.snow, 0f, -tile, w / u, h / u + 2f * tile, 2f, ay = (scroll % tile) - tile)
    } else {
        drawRect(Brush.verticalGradient(listOf(Color(0xFFEEF5FA), Color(0xFFDDE8F1))), size = size)
    }
    drawDecor(scroll, originX, trainPx, h, u)
    if (fx) safeFx { drawGroundFx(time, scroll, w, h, u, dark, storm) }
    for (st in stations) drawStation(st, originX, u)
    val ny = (centerOff - npc.camY) * u * z
    // The outside world (track, ground, trees) gets the full night tint first...
    translate(left = originX, top = ny) {
        scale(scaleX = z, scaleY = z, pivot = Offset.Zero) { drawTrack(scroll, npc.trainLen) }
    }
    if (dark > 0.01f) drawRect(Color(0xFF0B1B3A).copy(alpha = (dark * 1.9f).coerceAtMost(0.8f)), size = size)
    // light spilling out of the windows onto the dark ground
    if (dark > 0.01f) {
        translate(left = originX, top = ny) {
            scale(scaleX = z, scaleY = z, pivot = Offset.Zero) { drawWindowLight(look.cars, dark) }
        }
    }
    // ...and the lit train interior is drawn on top, only slightly dimmed and warmed by its lamps.
    translate(left = originX, top = ny) {
        scale(scaleX = z, scaleY = z, pivot = Offset.Zero) {
            drawTrain(tier, look, npc, time, boosting)
            if (npc2 != null) drawNpc(npc2, Color(0xFF5BBE7A), Color(0xFFF2C94C))
            drawNpc(npc)
        }
    }
    if (dark > 0.01f) {
        val trainH = npc.trainLen * u * z
        drawRect(Color(0xFF0B1B3A).copy(alpha = dark * 0.3f), Offset(originX, ny), Size(trainPx, trainH))
        drawRect(Color(0xFFFFB866).copy(alpha = dark * 0.22f), Offset(originX, ny), Size(trainPx, trainH), blendMode = BlendMode.Plus)
        val cx = originX + trainPx / 2f
        val beam = Path().apply {
            moveTo(cx - 40f * u * z, ny + 4f * u * z); lineTo(cx + 40f * u * z, ny + 4f * u * z)
            lineTo(cx + 110f * u * z, ny - 190f * u * z); lineTo(cx - 110f * u * z, ny - 190f * u * z); close()
        }
        drawPath(beam, Brush.verticalGradient(listOf(Color.Transparent, Color(0xFFFFF3B0).copy(alpha = dark * 1.4f)), startY = ny - 190f * u * z, endY = ny))
    }
    if (aurora) drawAurora(time, w, h)
    drawSnowfall(time, w, h, u, storm)
    if (fx && w > 4f && h > 4f) safeFx { drawPostFx(w, h, dark, storm) }
    if (npc.trainLen > npc.viewH + 1f) { // scroll bar: the train is taller than the screen
        val frac = npc.viewH / npc.trainLen
        val barH = h * frac
        val barY = (h * (npc.camY / npc.trainLen)).coerceIn(0f, h - barH)
        drawRoundRect(Color(0x55203040), Offset(w - 7f * u, barY), Size(4f * u, barH), CornerRadius(2f * u, 2f * u))
    }
    if (boosting) drawSpeedLines(time, originX, trainPx, w, h, u)
}

// ---- post-processing helpers (can be switched off in Settings) ----
private var fxOn = true
private var fxDark = 0f
private var fxBroken = false // set if a post-processing effect ever throws, so it is skipped from then on

private inline fun DrawScope.safeFx(block: () -> Unit) {
    if (!fxOn || fxBroken) return
    try {
        block()
    } catch (e: Exception) {
        fxBroken = true
    }
}

/** Additive light bloom around a light source, in train-space dp. */
private fun DrawScope.glow(x: Float, y: Float, r: Float, color: Color, strength: Float) {
    if (strength <= 0.01f || r <= 0f) return
    safeFx {
        val u = density
        val c = Offset(x * u, y * u)
        drawCircle(
            Brush.radialGradient(listOf(color.copy(alpha = strength.coerceIn(0f, 1f)), Color.Transparent), center = c, radius = r * u),
            radius = r * u, center = c, blendMode = BlendMode.Plus,
        )
    }
}

/** Cloud shadows drifting over the snow, and twinkling snow crystals in daylight. */
private fun DrawScope.drawGroundFx(time: Float, scroll: Float, w: Float, h: Float, u: Float, dark: Float, storm: Float) {
    for (i in 0 until 3) {
        val x = ((i * 0.37f + 0.1f) * w + sin(time * 0.05f + i) * 40f * u)
        val y = ((scroll * 0.35f + i * 380f) % (h / u + 300f)) * u - 150f * u
        drawOval(Color(0x16203050), Offset(x - 130f * u, y - 70f * u), Size(260f * u, 140f * u))
    }
    if (dark < 0.12f && storm < 0.3f) {
        for (i in 0 until 26) {
            val fx = ((i * 0.7548777f) % 1f) * w
            val fy = ((((i * 0.5698403f) % 1f) * h + scroll * u) % h)
            val a = max(0f, sin(time * 2.2f + i * 1.7f))
            if (a > 0.2f) {
                val s = (1.2f + a) * u
                drawLine(Color.White.copy(alpha = a * 0.9f), Offset(fx - s, fy), Offset(fx + s, fy), 0.9f * u)
                drawLine(Color.White.copy(alpha = a * 0.9f), Offset(fx, fy - s), Offset(fx, fy + s), 0.9f * u)
            }
        }
    }
}

/** Screen-space finishing: colour grading, warm sunset light and a vignette (frosty during storms). */
private fun DrawScope.drawPostFx(w: Float, h: Float, dark: Float, storm: Float) {
    // cool daylight grade, fading out as night falls
    drawRect(Color(0xFFBFDFFF).copy(alpha = 0.06f * (1f - dark / 0.42f)), size = size)
    // warm sunset or sunrise light during dusk and dawn
    val mid = 1f - kotlin.math.abs(dark / 0.42f * 2f - 1f)
    if (dark > 0.01f && dark < 0.41f) drawRect(Color(0xFFFF8A3D).copy(alpha = 0.16f * mid), size = size)
    // vignette
    val c = Offset(w / 2f, h / 2f)
    val rad = sqrt(w * w + h * h) / 2f
    drawRect(
        Brush.radialGradient(
            listOf(Color.Transparent, Color.Transparent, Color(0xFF0B1424).copy(alpha = 0.30f + dark * 0.6f)),
            center = c, radius = rad,
        ),
        size = size,
    )
    if (storm > 0f) {
        drawRect(
            Brush.radialGradient(
                listOf(Color.Transparent, Color.Transparent, Color.White.copy(alpha = 0.45f * storm)),
                center = c, radius = rad,
            ),
            size = size,
        )
    }
}

private fun DrawScope.drawAurora(time: Float, w: Float, h: Float) {
    for (i in 0 until 3) {
        val p = Path()
        p.moveTo(0f, 0f)
        var x = 0f
        while (x <= w + 20f) {
            p.lineTo(x, h * (0.06f + 0.05f * i) + sin(x * 0.012f + time * 0.7f + i * 1.7f) * h * 0.025f)
            x += 20f
        }
        p.lineTo(w, 0f)
        p.close()
        val c = if (i == 1) Color(0xFFB197FC) else Color(0xFF38F2A2)
        drawPath(p, Brush.verticalGradient(listOf(c.copy(alpha = 0.38f), Color.Transparent), startY = 0f, endY = h * 0.3f))
    }
}

/** A platform with a small shelter and waiting passengers, drawn next to the train. */
private fun DrawScope.drawStation(st: Station, originX: Float, u: Float) {
    val pw = 34f * u
    if (originX < pw + 10f * u) return
    val x = originX - pw - 6f * u
    val y = st.y * u
    val len = 190f * u
    drawRect(Color(0x33203040), Offset(x + 3f * u, y - len / 2f + 3f * u), Size(pw, len))
    drawRect(Color(0xFFB9C3CC), Offset(x, y - len / 2f), Size(pw, len))
    val art = sceneArt
    if (art != null) {
        withTransform({ translate(x + 3f * u, y - len / 2f + 3f * u) }) {
            drawRect(art.concrete, Offset.Zero, Size(pw - 6f * u, len - 6f * u))
        }
    } else {
        drawRect(Color(0xFFD7DFE6), Offset(x + 3f * u, y - len / 2f + 3f * u), Size(pw - 6f * u, len - 6f * u))
    }
    drawRect(Color(0xFFF2C94C), Offset(x + pw - 5f * u, y - len / 2f), Size(3f * u, len)) // safety line
    // shelter roof with snow
    val roof = sceneSprites?.stationRoof
    if (roof != null) {
        drawSprite(roof, x, y - 44f * u, 26f * u, 88f * u)
    } else {
        drawRoundRect(Color(0xFF8A5F3A), Offset(x + 4f * u, y - 40f * u), Size(18f * u, 80f * u), CornerRadius(3f * u, 3f * u))
        drawRoundRect(Color(0xFFF4F9FC), Offset(x + 5f * u, y - 38f * u), Size(16f * u, 30f * u), CornerRadius(3f * u, 3f * u))
    }
    if (st.stop) {
        // storm shelter: a warm lamp and a red sign
        drawCircle(
            Brush.radialGradient(listOf(Color(0x99FFC46B), Color.Transparent), Offset(x + 12f * u, y + 52f * u), 46f * u),
            46f * u, Offset(x + 12f * u, y + 52f * u), blendMode = BlendMode.Plus,
        )
        drawCircle(Color(0xFF3A3F47), 4.5f * u, Offset(x + 12f * u, y + 52f * u))
        drawCircle(Color(0xFFFFE680), 3f * u, Offset(x + 12f * u, y + 52f * u))
        drawRoundRect(Color(0xFFE5484D), Offset(x + 4f * u, y + 68f * u), Size(26f * u, 12f * u), CornerRadius(2f * u, 2f * u))
        drawRect(Color.White, Offset(x + 8f * u, y + 73f * u), Size(18f * u, 2f * u))
    }
    // passengers seen from above; at a storm stop they walk over and board the train
    val cols = listOf(Color(0xFFE5484D), Color(0xFF2F8FE0), Color(0xFF3FAE5A), Color(0xFFE8890C))
    for (i in 0 until 4) {
        val py = y - 70f * u + i * 22f * u
        val prog = if (st.stop && st.dwell > 0f) ((st.dwell - 0.6f - i * 0.9f) / 2.2f).coerceIn(0f, 1f) else 0f
        if (prog >= 1f) continue
        val px = x + 25f * u + (originX + 4f * u - (x + 25f * u)) * prog
        drawCircle(Color(0x33000000), 5.5f * u, Offset(px, py + 1.5f * u))
        drawCircle(cols[i], 5f * u, Offset(px, py))
        drawCircle(Color(0xFFF2C9A0), 2.6f * u, Offset(px, py - 0.5f * u))
    }
}

private fun DrawScope.drawDecor(scroll: Float, originX: Float, trainPx: Float, h: Float, u: Float) {
    if (originX < 24f * u) return
    for (d in DECOR) {
        val r = d.r * u
        val span = max(0f, originX - 2f * r)
        val x = if (d.side == 0) r + d.fx * span else originX + trainPx + r + d.fx * span
        val base = (d.y + scroll) % DECOR_PERIOD
        var k = -1
        while (true) {
            val y = (base + k * DECOR_PERIOD) * u
            if (y > h + r) break
            if (y > -r) drawDecorItem(d.kind, x, y, r)
            k++
        }
    }
}

private fun DrawScope.starPath(cx: Float, cy: Float, rOut: Float, rIn: Float, n: Int, rot: Float): Path {
    val p = Path()
    for (i in 0 until n * 2) {
        val ang = rot + i * PI_F / n
        val rr = if (i % 2 == 0) rOut else rIn
        val px = cx + cos(ang) * rr
        val py = cy + sin(ang) * rr
        if (i == 0) p.moveTo(px, py) else p.lineTo(px, py)
    }
    p.close()
    return p
}

private fun DrawScope.drawDecorItem(kind: Int, x: Float, y: Float, r: Float) {
    val seed = (x * 0.013f + r)
    val art = sceneArt
    if (art != null && kind != 4) {
        val pick = ((x / density).toInt() + (r * 7f).toInt()) and 0x7fffffff
        when (kind) {
            2 -> sprite(art.rocks[pick % art.rocks.size], x, y, r / 0.3f)
            3 -> sprite(art.shrub, x, y, r / 0.31f)
            else -> sprite(art.pines[pick % art.pines.size], x, y, r / 0.36f)
        }
        return
    }
    when (kind) {
        4 -> { // snow drift
            drawOval(Color(0xFFD3E2EE), Offset(x - r * 1.5f, y - r * 0.55f), Size(r * 3f, r * 1.1f))
            drawOval(Color(0xFFF7FBFE), Offset(x - r * 1.35f, y - r * 0.5f), Size(r * 2.6f, r * 0.85f))
        }
        2 -> { // rock with a snow cap
            drawOval(Color(0x33203040), Offset(x - r * 0.8f, y - r * 0.35f), Size(r * 2.1f, r * 1.4f))
            drawOval(Color(0xFF7D8A96), Offset(x - r, y - r * 0.75f), Size(r * 2f, r * 1.5f))
            drawOval(Color(0xFFA3AFBA), Offset(x - r * 0.85f, y - r * 0.7f), Size(r * 1.5f, r * 1.0f))
            drawOval(Color(0xFFF4F9FC), Offset(x - r * 0.6f, y - r * 0.7f), Size(r * 1.2f, r * 0.6f))
        }
        3 -> { // shrub
            drawOval(Color(0x33203040), Offset(x - r * 0.9f, y - r * 0.2f), Size(r * 2.2f, r * 1.4f))
            drawCircle(Color(0xFF3B5E4F), r * 0.8f, Offset(x - r * 0.45f, y))
            drawCircle(Color(0xFF486F5C), r * 0.85f, Offset(x + r * 0.4f, y + r * 0.1f))
            drawCircle(Color(0xFF557F69), r * 0.7f, Offset(x, y - r * 0.4f))
            drawCircle(Color(0xFFF4F9FC), r * 0.35f, Offset(x - r * 0.1f, y - r * 0.55f))
        }
        else -> { // pine seen from above: soft shadow, layered needle rings, snow dusting
            drawOval(Color(0x30203040), Offset(x - r * 0.45f, y - r * 0.35f), Size(r * 2.1f, r * 1.9f))
            val rings = listOf(
                Color(0xFF244B41), Color(0xFF2F6052), Color(0xFF3E7864), Color(0xFF54927B),
            )
            for (i in rings.indices) {
                val rr = r * (1f - i * 0.22f)
                drawPath(starPath(x, y, rr, rr * 0.66f, 11, seed + i * 0.35f), rings[i])
            }
            drawCircle(Color(0xFF6BA891), r * 0.12f, Offset(x, y))
            for (i in 0 until 5) {
                val ang = seed * 3f + i * 1.26f
                val d = r * (0.45f + 0.12f * (i % 2))
                drawCircle(Color.White.copy(alpha = 0.8f), r * 0.14f, Offset(x + cos(ang) * d, y + sin(ang) * d))
            }
            drawCircle(Color.White.copy(alpha = 0.85f), r * 0.2f, Offset(x - r * 0.12f, y - r * 0.14f))
        }
    }
}

private fun DrawScope.drawTrack(scroll: Float, len: Float) {
    val cx = CAR_W / 2f
    val top = -900f
    val total = len + 1800f
    val art = sceneArt
    if (art != null) {
        // ballast, wooden sleepers and steel rails from one 66 x 28 dp tile
        texRect(art.track, cx - 33f, top, 66f, total, 4f, ax = cx - 33f, ay = scroll % 28f)
        return
    }
    // gravel bed with darker edges
    box(Color(0xFF7C8793), cx - 33f, top, 66f, total)
    box(Color(0xFF99A5B0), cx - 30f, top, 60f, total)
    // sleepers: ids stay attached to the ground as the track scrolls
    val n = (scroll / 14f).toInt()
    val off = scroll % 14f
    var y = top - 2f + off
    var k = 0
    while (y < len + 900f) {
        val id = n - k
        val dark = (id * 7 + 3) % 5 == 0
        box(Color(0x33000000), cx - 24f, y + 1.5f, 50f, 4.5f, 1f)
        box(if (dark) Color(0xFF5A4A3B) else Color(0xFF6E5B49), cx - 25f, y, 50f, 4.5f, 1f)
        box(Color(0x22FFFFFF), cx - 25f, y, 50f, 1f)
        y += 14f
        k++
    }
    // steel rails with a bright top edge
    for (rx in listOf(cx - 16f, cx + 12f)) {
        box(Color(0x33000000), rx + 1.5f, top, 4f, total)
        box(Color(0xFF4A5560), rx, top, 4f, total)
        box(Color(0xFFC5CED6), rx + 1.2f, top, 1.2f, total)
    }
}

private fun DrawScope.drawTrain(tier: TrainTier, look: Look, npc: Npc, time: Float, boosting: Boolean) {
    val body = Color(tier.body)
    val accent = Color(tier.accent)
    val cars = look.cars
    drawNose(body, accent, look.plow)
    for (i in 0 until cars) {
        val top = NOSE + i * PITCH
        // skip cars that are off screen (each car draws several layers)
        if (top + CAR_H < npc.camY - 80f || top > npc.camY + npc.viewH + 80f) continue
        val floor: Color
        val plank: Color
        when (i) {
            0 -> { floor = Color(0xFF98A3AD); plank = Color(0xFF8A949E) }
            1 -> { floor = Color(0xFFE3DCCB); plank = Color(0xFFD3CBB8) }
            else -> when ((i - 2) % 4) {
                1 -> { floor = Color(0xFFD9CBB4); plank = Color(0xFFC9B99F) }   // passenger lounge
                2 -> { floor = Color(0xFFB9CDB0); plank = Color(0xFFA6BC9D) }   // greenhouse
                3 -> { floor = Color(0xFFA9B1B9); plank = Color(0xFF99A2AB) }   // workshop
                else -> { floor = Color(0xFFC49A6C); plank = Color(0xFFAF8559) } // cargo hold
            }
        }
        drawCarShell(top, body, accent, floor, plank, metal = i == 0)
        when (i) {
            0 -> drawEngineCar(top, look, npc, time, boosting)
            1 -> drawUtilityCar(top, look, npc, time)
            else -> drawModuleCar(top, i, look, time)
        }
        glow(AISLE_X, top + CAR_H / 2f, 90f, Color(0xFFFFD9A0), fxDark * 1.1f) // warm ceiling lamp at night
        if (i < cars - 1) drawVestibule(top + CAR_H)
    }
}

private fun DrawScope.drawNose(body: Color, accent: Color, plow: Int) {
    val u = density
    val noseImg = sceneSprites?.noseFill
    if (noseImg != null) {
        drawSprite(noseImg, -6f * u, -6f * u, 202f * u, 44f * u, tint = body)
        sceneSprites?.noseLine?.let { drawSprite(it, -6f * u, -6f * u, 202f * u, 44f * u) }
        glow(56f, 15f, 30f, Color(0xFFFFE680), 0.25f + fxDark * 1.6f)
        glow(134f, 15f, 30f, Color(0xFFFFE680), 0.25f + fxDark * 1.6f)
        if (plow > 0) {
            box(Color(0xFF6B4A3A), 37f, -1f, 116f, 7f, 3.5f)
            box(Color(0xFFA9DDF2), 38f, 0f, 114f, 5f, 2.5f)
        }
        return
    }
    val p = Path().apply {
        moveTo(16f * u, (NOSE + 2f) * u)
        lineTo(46f * u, 4f * u)
        lineTo(144f * u, 4f * u)
        lineTo(174f * u, (NOSE + 2f) * u)
        close()
    }
    drawPath(p, body)
    dot(Color(0x33FFE680), 56f, 15f, 10f)
    dot(Color(0x33FFE680), 134f, 15f, 10f)
    box(Color(0x22FFFFFF), 46f, 4f, 98f, 4f, 2f)
    glow(56f, 15f, 30f, Color(0xFFFFE680), 0.25f + fxDark * 1.6f)
    glow(134f, 15f, 30f, Color(0xFFFFE680), 0.25f + fxDark * 1.6f)
    dot(Color(0xFFFFE680), 56f, 15f, 5f)
    dot(Color(0xFFFFE680), 134f, 15f, 5f)
    box(accent, 70f, 10f, 50f, 4f, 2f)
    if (plow > 0) box(Color(0xFF9FD8F0), 38f, 0f, 114f, 6f, 3f)
}

private fun DrawScope.drawCarShell(top: Float, body: Color, accent: Color, floor: Color, plank: Color, metal: Boolean = false) {
    val walls = sceneSprites?.carFill
    val tex = sceneArt
    if (walls != null && tex != null) {
        // textured floor, then the 3D-shaded walls (tinted with the train colour) with glass windows
        texRect(if (metal) tex.metal else tex.wood, 7f, top + 7f, CAR_W - 14f, CAR_H - 14f, 4f, ax = 7f, ay = top + 7f, r = 4f)
        box(floor.copy(alpha = 0.12f), 7f, top + 7f, CAR_W - 14f, CAR_H - 14f, 4f)
        val u = density
        drawSprite(walls, -8f * u, (top - 8f) * u, 206f * u, 132f * u, tint = body)
        sceneSprites?.carLine?.let { drawSprite(it, -8f * u, (top - 8f) * u, 206f * u, 132f * u) }
        box(accent.copy(alpha = 0.85f), 30f, top + 2.2f, CAR_W - 60f, 2.2f, 1.1f)
        return
    }
    // layered soft shadow on the ground
    box(Color(0x1A101820), 8f, top + 10f, CAR_W, CAR_H, 14f)
    box(Color(0x26101820), 4f, top + 5f, CAR_W, CAR_H, 12f)
    box(body, 0f, top, CAR_W, CAR_H, 12f)
    val art = sceneArt
    if (art != null) {
        // weathered paint and a soft metallic sheen
        texRect(art.grime, 0f, top, CAR_W, CAR_H, 4f, ay = top, r = 12f, blend = BlendMode.Multiply)
        val u = density
        drawRoundRect(
            Brush.horizontalGradient(listOf(Color(0x30FFFFFF), Color.Transparent, Color(0x26000000)), startX = 0f, endX = CAR_W * u),
            Offset(0f, top * u), Size(CAR_W * u, CAR_H * u), CornerRadius(12f * u, 12f * u),
        )
    }
    box(Color(0x26FFFFFF), 0f, top, CAR_W, 6f, 12f)            // roof edge highlight
    box(Color(0x22000000), 0f, top + CAR_H - 6f, CAR_W, 6f, 12f) // lower edge shade
    if (art != null) {
        texRect(if (metal) art.metal else art.wood, 7f, top + 7f, CAR_W - 14f, CAR_H - 14f, 4f, ax = 7f, ay = top + 7f, r = 4f)
        box(floor.copy(alpha = if (metal) 0.25f else 0.38f), 7f, top + 7f, CAR_W - 14f, CAR_H - 14f, 4f)
    } else {
        box(floor, 7f, top + 7f, CAR_W - 14f, CAR_H - 14f, 4f)
        var y = top + 19f
        while (y < top + CAR_H - 8f) {
            box(plank, 7f, y, CAR_W - 14f, 1.2f)
            y += 12f
        }
    }
    // inset shading so the floor looks recessed
    box(Color(0x30000000), 7f, top + 7f, CAR_W - 14f, 5f, 4f)
    box(Color(0x1E000000), 7f, top + 7f, 4f, CAR_H - 14f, 2f)
    box(Color(0x18FFFFFF), 7f, top + CAR_H - 11f, CAR_W - 14f, 4f, 2f)
    var wy = top + 14f
    while (wy < top + CAR_H - 20f) {
