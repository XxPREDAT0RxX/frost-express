            val t = (time * 0.7f + k / 3f) % 1f
            val strength = if (cooking) 0.7f else 0.25f
            dot(Color.White.copy(alpha = (1f - t) * strength), 138f + (k - 1) * 3f, top + 30f - t * 14f, 3f + t * 4f)
