/** How many riders sit in [car] right now (0 in the engine; the rest spread across the other cars). */
private fun paxInCar(car: Int, cars: Int): Int {
    if (car == 0) return 0
    val nonEngine = max(1, cars - 1)
    val base = scenePassengers / nonEngine
    val extra = scenePassengers % nonEngine
    val idx = car - 1
    return (base + if (idx < extra) 1 else 0).coerceIn(0, Balance.SEATS_PER_CAR)
}

/** A forward-facing train seat seen from above, with its rider's head and shoulders if taken. */
private fun DrawScope.drawTrainSeat(cx: Float, cy: Float, pax0: ScenePax?, doorY: Float, kind: Int = 0) {
    val u = density
    pax0?.let { it.seatX = cx; it.seatY = cy; it.doorY = doorY }
    // a rider who has just boarded is still walking in: in through the car door, down the aisle, then to the seat
    var pax = pax0
    if (pax != null && sceneClock < pax.boardAt + BOARD_WALK_SEC) {
        val t = (sceneClock - pax.boardAt) / BOARD_WALK_SEC
        if (t >= 0f) {
            val sp = sceneSprites
            val pool = if (pax.warm && !sp?.summer.isNullOrEmpty()) sp!!.summer else sp?.survivors ?: emptyList()
            val full = sp?.chibiFull
            val img = if (!pax.warm && !full.isNullOrEmpty()) full[Math.floorMod(pax.sprite, full.size)]
                else if (pool.isNotEmpty()) pool[Math.floorMod(pax.sprite, pool.size)] else sp?.npc
            val a = 0.7f
            val wx = if (t < a) AISLE_X else AISLE_X + (cx - AISLE_X) * ((t - a) / (1f - a))
            val wy = if (t < a) doorY + (cy - doorY) * (t / a) else cy
            // down the aisle facing us, then a quick turn to walk sideways to the seat
            val turn = ((t - a) / 0.08f).coerceIn(0f, 1f).let { it * it * (3f - 2f * it) }
            val sideImg = if (!pax.warm) sp?.chibiSide?.let { l -> l.getOrNull(Math.floorMod(pax.sprite, l.size)) } else null
            sceneBoarders.add(BoardWalker(img, wx, wy, pax.sprite * 0.9f, t >= a && cx < AISLE_X, sideImg, turn * (if (cx < AISLE_X) -1f else 1f), if (!pax.warm) npcLook(pax.sprite) else null))
        }
        pax = null
    }
    // upholstery picks up the train's own colour, so every tier's coach looks a little different
    val tierCol = Color(TIERS[sceneTier.coerceIn(0, TIERS.lastIndex)].body)
    val fab = if (kind == 2) androidx.compose.ui.graphics.lerp(Color(0xFFA85A62), tierCol, 0.3f) else androidx.compose.ui.graphics.lerp(Color(0xFF7FA8CC), tierCol, 0.5f)
    val fabD = if (kind == 2) androidx.compose.ui.graphics.lerp(Color(0xFF7E3F49), tierCol, 0.3f) else androidx.compose.ui.graphics.lerp(Color(0xFF5C83A6), tierCol, 0.5f)
    // seat back and head-rest (behind the rider); a commuter bench (kind 1) has a shared back drawn by the car instead
    if (kind != 1) {
        box(Color(0xFF3E4A57), cx - 15f, cy - 17f, 30f, 26f, 7f)
        box(fabD, cx - 14f, cy - 16f, 28f, 24f, 6f)
        box(fab, cx - 14f, cy - 16f, 28f, 11f, 6f)
    }
    // a real cosy passenger (one of the survivor characters), sitting, facing out
    if (pax != null) {
        val sp = sceneSprites
        val pool = if (pax.warm && !sp?.summer.isNullOrEmpty()) sp!!.summer else sp?.survivors ?: emptyList()
        val img = if (pool.isNotEmpty()) pool[Math.floorMod(pax.sprite, pool.size)] else sp?.npc
        val chibis = sp?.chibis
        val seed = pax.sprite * 1.7f + cx * 0.13f + cy * 0.07f
        val look = if (!pax.warm) npcLook(pax.sprite) else null
        if (look != null) {
            // Blender NPC: breathes, sways and blinks; the cushion drawn next hides everything below the waist
            drawOval(Color(0x22000000), Offset((cx - 9f) * u, (cy + 7f) * u), Size(18f * u, 6f * u))
            drawNpcSeated(look, cx * u, (cy + NPC_SEAT_FEET) * u, NPC_SEAT_H * u, sceneClock + seed * 0.37f, (cy + 5f) * u)
        } else if (!pax.warm && !chibis.isNullOrEmpty()) {
            // flat chibi passenger: breathes, sways and blinks every few seconds
            val c = chibis[Math.floorMod(pax.sprite, chibis.size)]
            val period = 3.2f + Math.floorMod(pax.sprite * 7 + cx.toInt(), 5) * 0.45f
            val blink = ((sceneClock + seed * 0.61f) % period + period) % period < 0.13f
            val pic = if (blink) c.second else c.first
            val h = 23f
            val w = h * pic.width / pic.height
            drawOval(Color(0x22000000), Offset((cx - 9f) * u, (cy + 7f) * u), Size(18f * u, 6f * u))
            drawPuppet(pic, (cx - w / 2f) * u, (cy - 15f) * u, w * u, h * u, sceneClock, seed, cut = 0.6f)
        } else if (img != null) {
            // soft shadow, then the character; legs are hidden behind the seat cushion below
            drawOval(Color(0x22000000), Offset((cx - 9f) * u, (cy + 7f) * u), Size(18f * u, 6f * u))
            drawPuppet(img, (cx - 11f) * u, (cy - 16f) * u, 22f * u, 27f * u, sceneClock, seed)
        }
    }
    // seat cushion + armrests in front, covering the rider's legs so they read as seated
    box(Color(0xFF3E4A57), cx - 15f, cy + 4f, 30f, 14f, 6f)
    box(fab.copy(alpha = 0.95f), cx - 14f, cy + 5f, 28f, 12f, 5f)
    box(fabD, cx - 14f, cy + 5f, 28f, 4f, 3f)
    if (kind != 1) {
        box(Color(0xFF3E4A57), cx - 15f, cy - 4f, 3f, 20f, 1.5f)   // armrests
        box(Color(0xFF3E4A57), cx + 12f, cy - 4f, 3f, 20f, 1.5f)
    }
}

