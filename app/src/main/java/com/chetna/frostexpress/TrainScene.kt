/**
 * Fills a rectangle (dp, train or screen space) with a tiled texture of [pxPerDp] texture pixels per dp.
 * The texture is anchored at ([ax], [ay]) dp so it moves together with whatever it belongs to.
 */
private fun DrawScope.texRect(
    brush: ShaderBrush, x: Float, y: Float, w: Float, h: Float, pxPerDp: Float,
    ax: Float = 0f, ay: Float = 0f, r: Float = 0f, alpha: Float = 1f, blend: BlendMode = BlendMode.SrcOver,
) {
    val u = density
    val k = u / pxPerDp
    withTransform({ translate(ax * u, ay * u); scale(k, k, Offset.Zero) }) {
        val tl = Offset((x - ax) * u / k, (y - ay) * u / k)
        val sz = Size(w * u / k, h * u / k)
        if (r > 0f) drawRoundRect(brush, tl, sz, CornerRadius(r * u / k, r * u / k), alpha = alpha, blendMode = blend)
        else drawRect(brush, tl, sz, alpha = alpha, blendMode = blend)
    }
}

private fun DrawScope.sprite(img: ImageBitmap, cx: Float, cy: Float, side: Float) {
    val s = side.toInt().coerceAtLeast(1)
    drawImage(img, dstOffset = IntOffset((cx - side / 2f).toInt(), (cy - side / 2f).toInt()), dstSize = IntSize(s, s))
}

/** A car appears once its first upgrade is unlocked. */
private fun carCount(vm: GameViewModel): Int {
    var n = 2
    for (i in 2 until CAR_DEFS.size) {
        val first = CAR_DEFS[i][0]
        if (UPGRADES.firstOrNull { it.type == first }?.let { vm.isUnlocked(it) } == true) n = i + 1
    }
    return n
}
