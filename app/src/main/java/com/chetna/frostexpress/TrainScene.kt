/** A long platform with a station building, benches, lamp posts and waiting passengers, next to the train. */
/** A country road that runs alongside the line on the outer side, linking the stations.
 *  It is drawn continuously (not per station) so every stop sits on the same road. */
private fun DrawScope.drawStationRoad(scroll: Float, originX: Float, h: Float, u: Float) {
    val roadW = 20f * u
    val cx = originX - (ST_W + 70f + 30f) * u
    if (cx < roadW) return
    val left = cx - roadW / 2f
    // soft grass shoulders, then asphalt
    drawRect(Color(0xFF9BAE7E).copy(alpha = 0.45f), Offset(left - 6f * u, 0f), Size(roadW + 12f * u, h))
    drawRect(Color(0xFF5B626C), Offset(left, 0f), Size(roadW, h))
    drawRect(Color(0xFF6B727C), Offset(left + 1.5f * u, 0f), Size(roadW - 3f * u, h))
    // dashed centre line, scrolling with the world
    val dash = 24f; val gap = 20f; val period = dash + gap
    var y = -(((scroll % period) + period) % period) * u
    while (y < h) {
        drawRect(Color(0xFFF2C94C), Offset(cx - 1.6f * u, y), Size(3.2f * u, dash * u))
        y += period * u
    }
}

private fun DrawScope.drawStation(st: Station, originX: Float, u: Float) {
    val pw = ST_PW[st.type] * u
    val ext = ST_EXT[st.type]
    val x = originX - pw - 6f * u
    val y = st.y * u
    val len = ST_LEN * u
    val sp = sceneSprites
    drawRect(Color(0x33203040), Offset(x + 3f * u, y - len / 2f + 3f * u), Size(pw, len))
    drawRect(Color(0xFFA9B4BE), Offset(x, y - len / 2f), Size(pw, len))
    val art = sceneArt
    if (art != null) {
        withTransform({ translate(x + 3f * u, y - len / 2f + 3f * u) }) {
            drawRect(art.concrete, Offset.Zero, Size(pw - 6f * u, len - 6f * u))
        }
    } else {
        drawRect(Color(0xFFD7DFE6), Offset(x + 3f * u, y - len / 2f + 3f * u), Size(pw - 6f * u, len - 6f * u))
    }
    drawRect(Color(0xFF6B4A3A), Offset(x, y - len / 2f), Size(pw, len), style = Stroke(1.6f * u))
    drawRect(Color(0xFFF2C94C), Offset(x + pw - 6f * u, y - len / 2f), Size(3f * u, len)) // safety line
    // snow piled at both ends of the platform
    drawOval(Color.White, Offset(x - 4f * u, y - len / 2f - 10f * u), Size(pw + 8f * u, 22f * u))
    drawOval(Color.White, Offset(x - 4f * u, y + len / 2f - 12f * u), Size(pw + 8f * u, 22f * u))
    // station building on the outer half
    val bldg = sp?.stationBlds?.getOrNull(st.type)
    val bw = ST_BW[st.type]
    val bh = min(bw / ST_ASPECT[st.type], ST_LEN - 140f)
    if (bldg != null) {
        // the building stands on the outer half of the platform and reaches out over the grass
        drawOval(Color(0x2A203040), Offset(x - ext * u + 4f * u, y - bh / 2f * u + 6f * u), Size(bw * u, bh * u))
        drawSprite(bldg, x - ext * u + 1f * u, y - bh / 2f * u, bw * u, bh * u)
        // a covered walkway: posts along the platform holding up the canopy
        for (k in -3..3) {
            if (k == 0) continue
            val py = y + k * 62f * u
            drawRect(Color(0x33203040), Offset(x + pw * 0.80f - 2f * u, py - 1f * u), Size(7f * u, 7f * u))
            drawRect(Color(0xFF5A4636), Offset(x + pw * 0.80f - 3f * u, py - 3f * u), Size(6f * u, 6f * u))
        }
    } else {
        val old = sp?.stationBldg
        if (old != null) drawSprite(old, x + 1f * u, y - 48f * u, 34f * u, 90f * u)
        else sp?.stationRoof?.let { drawSprite(it, x, y - 44f * u, 26f * u, 88f * u) }
    }
    // benches and lamp posts
    sp?.stationBench?.let { b ->
        drawSprite(b, x + 6f * u, y - (bh / 2f + 26f) * u, 10f * u, 22f * u)
        drawSprite(b, x + 6f * u, y + (bh / 2f + 4f) * u, 10f * u, 22f * u)
    }
    for (ly in ST_LAMPS) {
        val lx = x + pw - 14f * u
        val img = sp?.stationLamp
        if (img != null) drawSprite(img, lx - 6f * u, y + ly * u - 6f * u, 12f * u, 12f * u)
        else { drawCircle(Color(0xFF5A6470), 5f * u, Offset(lx, y + ly * u)); drawCircle(Color(0xFFFFF3C4), 3f * u, Offset(lx, y + ly * u)) }
    }
    if (st.stop) {
        // storm shelter: a red sign
        drawRoundRect(Color(0xFFE5484D), Offset(x + 4f * u, y + 52f * u), Size(26f * u, 12f * u), CornerRadius(2f * u, 2f * u))
        drawRect(Color.White, Offset(x + 8f * u, y + 57f * u), Size(18f * u, 2f * u))
    }
    // a little parking lot on the outer side, linked to the road, with a few parked cars
    val parkLeft = x - (46f + ext) * u
    if (parkLeft > -20f * u) {
        val parkW = 42f * u
        val parkTop = y - 68f * u
        val parkH = 136f * u
        drawRect(Color(0xFF6E7681), Offset(parkLeft, parkTop), Size(parkW, parkH))
        drawRect(Color(0xFF5B626C), Offset(parkLeft, parkTop), Size(parkW, parkH), style = Stroke(1.4f * u))
        for (b in 0..3) drawRect(Color(0xFFE6E6E6).copy(alpha = 0.55f), Offset(parkLeft + 3f * u, parkTop + 6f * u + b * 34f * u), Size(parkW - 6f * u, 1.6f * u))
        // a short slip road from the main road into the lot
        drawRect(Color(0xFF5B626C), Offset(parkLeft - 26f * u, y - 7f * u), Size(26f * u, 14f * u))
        // parked cars (top-down), skipping one bay so it reads as a car park
        val carImg = sceneArt?.byName["car"]
        val carCols = listOf(Color(0xFFE5484D), Color(0xFF2F8FE0), Color(0xFF3FAE5A), Color(0xFFE8890C))
        for (b in 0..3) {
            if (b == 2) continue
            val cxp = parkLeft + 7f * u
            val cyp = parkTop + 5f * u + b * 34f * u
            if (carImg != null) drawSprite(carImg, cxp, cyp, 28f * u, 28f * u)
            else {
                drawRoundRect(carCols[b], Offset(cxp + 2f * u, cyp), Size(24f * u, 28f * u), CornerRadius(5f * u, 5f * u))
                drawRoundRect(Color(0xFFBFE0F0), Offset(cxp + 5f * u, cyp + 5f * u), Size(18f * u, 9f * u), CornerRadius(3f * u, 3f * u))
            }
        }
    }
    // a few people just waiting about on the platform (they are not travelling)
    for (i in 0 until st.waiting) {
        val py = y + (-ST_LEN / 2f + 60f + i * ((ST_LEN - 120f) / max(1, st.waiting - 1))) * u
        val px = x + pw * (0.30f + 0.12f * ((st.seed + i * 7) % 3))
        passenger(px, py, 1f, u, i + st.seed + 11, 0f, 0f)
    }
    // real riders: off through their car door to the building, and from the building to a car door
    val ent = Offset(x - ST_OUT[st.type] * u + bw * u - 4f * u, y + 6f * u)
    val laneX = x + pw * 0.62f
    fun doorAt(car: Int): Offset {
        val sy = sceneNyPx + (NOSE + car * PITCH - 6f) * u * sceneZoom
        return Offset(originX - 2f * u, y + (sy - sceneWorldPx - y) / sceneZoom)
    }
    val sp2 = sceneSprites ?: return
    fun walker(p: ScenePax, pts: List<Offset>, f: Float, alpha: Float) {
        if (alpha <= 0.01f) return
        val (pos, _) = walkPath(pts, f)
        var face = 0f
        for (k in -2..2) face += walkPath(pts, f + k * 0.025f).second
        face /= 5f
        val full = sp2.chibiFull
        drawOval(Color(0x33000000).copy(alpha = 0.18f * alpha), Offset(pos.x - 7f * u, pos.y + 7f * u), Size(14f * u, 5f * u))
        val look = if (!p.warm) npcLook(p.sprite) else null
        if (look != null) {
            drawNpc(look, pos.x, pos.y + 6f * u, NPC_PLATFORM_H * u, sceneClock + p.sprite * 0.37f, sceneClock * 9f + p.sprite, 1f, face, alpha)
        } else if (!p.warm && full.isNotEmpty()) {
            val img = full[Math.floorMod(p.sprite, full.size)]
            val side = sp2.chibiSide.getOrNull(Math.floorMod(p.sprite, sp2.chibiSide.size))
            val h = 29f * (img.height - 2 * MeshPuppet.PAD) / 322f
            drawChibi(img, side, pos.x, pos.y + 6f * u, h * u, sceneClock + p.sprite * 0.37f, sceneClock * 9f + p.sprite, 1f, face, alpha, spriteXScale)
        } else passenger(pos.x, pos.y, alpha, u, p.sprite, sceneClock * 9f, 1f, face < 0f, facing = face)
    }
    for (lv in sceneLeavers) {
        if (lv.station !== st) continue
        val t0 = lv.standAt + LEAVE_IN_SEC
        val f = (sceneClock - t0) / PLATFORM_WALK_SEC
        if (f < 0f || f > 1f) continue
        val d = doorAt(carOfSlot(lv.slot).coerceAtMost(sceneCarCount - 1))
        val pts = listOf(d, Offset(laneX, d.y), Offset(laneX, ent.y), ent)
        walker(lv.pax, pts, f, (f / 0.08f).coerceIn(0f, 1f) * (1f - ((f - 0.85f) / 0.15f).coerceIn(0f, 1f)))
    }
    for (ar in st.arrivals) {
        val f = (sceneClock - ar.leaveAt) / PLATFORM_WALK_SEC
        if (f < 0f || f > 1f) continue
        val d = doorAt(ar.car.coerceAtMost(sceneCarCount - 1))
        val pts = listOf(ent, Offset(laneX, ent.y), Offset(laneX, d.y), d)
        walker(ar.pax, pts, f, (f / 0.12f).coerceIn(0f, 1f) * (1f - ((f - 0.94f) / 0.06f).coerceIn(0f, 1f)))
    }
}


/** A character sprite with a walking gait: a waddle (rotation about the feet), a hop on every step and a little squash and stretch.
 *  [phase] advances with distance walked; [moving] 0..1 fades the gait in and out; [flip] mirrors when heading left. */
private fun DrawScope.drawWalkingSprite(img: ImageBitmap, cx: Float, feetY: Float, w: Float, h: Float, phase: Float, moving: Float, flip: Boolean = false, alpha: Float = 1f) {
    val u = density
    val step = sin(phase)
    val hop = kotlin.math.abs(step) * 2.4f * moving
    val sq = 1f + 0.05f * sin(phase * 2f + 1.57f) * moving
    val rot = step * 7f * moving
    withTransform({
        if (flip) scale(-1f, 1f, Offset(cx, feetY))
        rotate(rot, Offset(cx, feetY))
        scale(1f / sq, sq, Offset(cx, feetY))
    }) {
        drawSprite(img, cx - w / 2f * u, feetY - (h + hop) * u, w * u, h * u, alpha = alpha)
    }
}

/** One waiting or leaving passenger, drawn as a real cosy character (same faces as inside the train). */
private fun DrawScope.passenger(px: Float, py: Float, alpha: Float, u: Float, seed: Int, walkPhase: Float = 0f, moving: Float = 0f, flip: Boolean = false, side: Boolean = false, facing: Float = 0f) {
    if (alpha <= 0.01f) return
    drawOval(Color(0x33000000).copy(alpha = 0.18f * alpha), Offset(px - 7f * u, py + 7f * u), Size(14f * u, 5f * u))
    val sp = sceneSprites
    val look = if (!sceneWarm) npcLook(seed) else null
    if (look != null) {
        drawNpc(look, px, py + 6f * u, NPC_PLATFORM_H * u, sceneClock + seed * 0.37f, walkPhase, moving, facing, alpha)
        return
    }
    val full = sp?.chibiFull
    if (!sceneWarm && !full.isNullOrEmpty()) {
        val img = full[Math.floorMod(seed, full.size)]
        val h = 29f * (img.height - 2 * MeshPuppet.PAD) / 322f
        val sideImg = sp!!.chibiSide.let { l -> l.getOrNull(Math.floorMod(seed, l.size)) }
        drawChibi(img, sideImg, px, py + 6f * u, h * u, sceneClock + seed * 0.37f, walkPhase, moving, facing, alpha, spriteXScale)
        return
    }
    val walkers = sp?.walkers
    if (side && moving > 0f && !walkers.isNullOrEmpty() && !sceneWarm) {
        val ch = walkers[Math.floorMod(seed, walkers.size)]
        val fr = ch[Math.floorMod((walkPhase * 0.9f).toInt(), 4)]
        val h = 25f * (0.8f + 0.2f * (fr.height / 232f).coerceAtMost(1.2f))
        val w = h * fr.width / fr.height
        withTransform({ if (flip) scale(-1f, 1f, Offset(px, py)) }) {
            drawSprite(fr, px - w / 2f * u, py + 6f * u - h * u, w * u, h * u, alpha = alpha)
        }
        return
    }
    val pool = if (sceneWarm && !sp?.summer.isNullOrEmpty()) sp!!.summer else sp?.survivors ?: emptyList()
    val img = if (pool.isNotEmpty()) pool[Math.floorMod(seed, pool.size)] else sp?.npc
    if (img != null) {
        drawWalkingSprite(img, px, py + 6f * u, 18f, 22f, walkPhase, moving, flip, alpha)
    } else {
        drawCircle(Color(0xFF6B4A3A).copy(alpha = alpha), 5.6f * u, Offset(px, py))
        drawCircle(Color(0xFFF2C9A0).copy(alpha = alpha), 2.4f * u, Offset(px, py - 0.5f * u))
    }
}

/** Lamp light and warm windows; drawn after the night tint so they really glow. [on] 0..1. */
private fun DrawScope.drawStationLights(st: Station, originX: Float, u: Float, on: Float) {
    val pw = ST_PW[st.type] * u
    val x = originX - pw - 6f * u
    val y = st.y * u
    if (y < -ST_LEN * u || y > size.height + ST_LEN * u) return
    val warm = Color(0xFFFFC46B)
    for (ly in ST_LAMPS) {
        val c = Offset(x + pw - 14f * u, y + ly * u)
        val r = 38f * u
        drawCircle(Brush.radialGradient(listOf(warm.copy(alpha = 0.3f * on), Color.Transparent), c, r), r, c, blendMode = BlendMode.Plus)
        drawCircle(Color(0xFFFFF3C4).copy(alpha = on), 3f * u, c)
    }
    // light from the station windows spilling onto the platform
    for (wy in listOf(-26f, 10f)) {
        val c = Offset(x + (ST_BW[st.type] * 0.5f - ST_OUT[st.type]) * u, y + wy * 2.6f * u)
        val r = 34f * u
        drawOval(
            Brush.radialGradient(listOf(warm.copy(alpha = 0.26f * on), Color.Transparent), c, r),
            Offset(c.x - r, c.y - r * 0.8f), Size(r * 2f, r * 1.6f), blendMode = BlendMode.Plus,
        )
    }
}

private fun DrawScope.drawDecor(scroll: Float, originX: Float, trainPx: Float, h: Float, u: Float) {
    if (originX < 24f * u) return
    // lay the scenery out for the train's normal place, then slide it with the station pan,
    // so trees keep their spot (and their kind) while the view moves over to a station
    val pan = sceneStationPan * size.width * 0.21f
    val o0 = originX - pan
    for ((di, d) in DECOR.withIndex()) {
        val r = d.r * u
        val span = max(0f, o0 - 2f * r)
        val x = pan + if (d.side == 0) r + d.fx * span else o0 + trainPx + r + d.fx * span
        val base = (d.y + scroll) % DECOR_PERIOD
        var k = -1
        while (true) {
            val y = (base + k * DECOR_PERIOD) * u
            if (y > h + r) break
            if (y > -r) drawDecorItem(d.kind, x, y, r, zoneAt(scroll - y / u), di)
            k++
        }
    }
}

private fun DrawScope.starPath(cx: Float, cy: Float, rOut: Float, rIn: Float, n: Int, rot: Float): Path {
    val p = Path()
    for (i in 0 until n * 2) {
        val ang = rot + i * PI_F / n
        val rr = if (i % 2 == 0) rOut else rIn
        val px = cx + cos(ang) * rr
        val py = cy + sin(ang) * rr
        if (i == 0) p.moveTo(px, py) else p.lineTo(px, py)
    }
    p.close()
    return p
}

private fun DrawScope.drawDecorItem(kind: Int, x: Float, y: Float, r: Float, zone: Int = 0, id: Int = -1) {
    val seed = (x * 0.013f + r)
    val art = sceneArt
    val z = ZONES[zone]
    if (art != null && kind == 4 && z.lakes) {
        art.byName["lake"]?.let { lake ->
            val w = r * 4.2f
            drawImage(lake, dstOffset = IntOffset((x - w / 2f).toInt(), (y - w / 3f).toInt()), dstSize = IntSize(w.toInt(), (w * 2f / 3f).toInt()))
            return
        }
    }
    // kind 4 is a ground patch: a frozen lake in the snowfields, nothing in the green/warm lands
    if (art != null && kind == 4 && !z.lakes) return
    val names = z.slots[kind]
    if (art != null && kind != 4 && names != null && art.byName.isNotEmpty()) {
        val pick = (if (id >= 0) id * 7919 else (x / density).toInt() + (r * 7f).toInt()) and 0x7fffffff
        val name = names[(pick / 3) % names.size]
        val img = art.byName[name]
        if (img != null) {
            val side = when (kind) { 1 -> r / 0.4f; 2, 6 -> r / 0.31f; else -> r / 0.35f }
            sprite(img, x, y, side)
            if (name == "v_house_a" && fxDark > 0.02f) {
                val c = Offset(x + 0.16f * side, y + 0.08f * side)
                val rr = side * 0.3f
                drawCircle(Brush.radialGradient(listOf(Color(0xFFFFB066).copy(alpha = 0.55f * (fxDark / 0.42f).coerceIn(0f, 1f)), Color.Transparent), c, rr), rr, c, blendMode = BlendMode.Plus)
            }
            if (name == "campfire" && fxDark > 0.02f) {
                val c = Offset(x, y)
                val rr = side * 0.9f
                drawCircle(Brush.radialGradient(listOf(Color(0xFFFFB066).copy(alpha = 0.5f * (fxDark / 0.42f).coerceIn(0f, 1f)), Color.Transparent), c, rr), rr, c, blendMode = BlendMode.Plus)
            }
            return
        }
    }
    if (art != null && kind != 4) {
        val pick = (if (id >= 0) id * 7919 else (x / density).toInt() + (r * 7f).toInt()) and 0x7fffffff
        when (kind) {
            1 -> sprite(art.wrecks[(pick / 3) % art.wrecks.size], x, y, r / 0.4f)
            2 -> sprite(art.rocks[pick % art.rocks.size], x, y, r / 0.3f)
            3 -> sprite(art.dead[pick % art.dead.size], x, y, r / 0.34f)
            5 -> sprite(art.ice, x, y, r / 0.34f)
            6 -> sprite(art.shrub, x, y, r / 0.31f)
            else -> sprite(art.pines[pick % art.pines.size], x, y, r / 0.36f)
        }
        return
    }
    when (kind) {
        4 -> { // snow drift
            drawOval(Color(0xFFD3E2EE), Offset(x - r * 1.5f, y - r * 0.55f), Size(r * 3f, r * 1.1f))
            drawOval(Color(0xFFF7FBFE), Offset(x - r * 1.35f, y - r * 0.5f), Size(r * 2.6f, r * 0.85f))
        }
        2 -> { // rock with a snow cap
            drawOval(Color(0x33203040), Offset(x - r * 0.8f, y - r * 0.35f), Size(r * 2.1f, r * 1.4f))
            drawOval(Color(0xFF7D8A96), Offset(x - r, y - r * 0.75f), Size(r * 2f, r * 1.5f))
            drawOval(Color(0xFFA3AFBA), Offset(x - r * 0.85f, y - r * 0.7f), Size(r * 1.5f, r * 1.0f))
            drawOval(Color(0xFFF4F9FC), Offset(x - r * 0.6f, y - r * 0.7f), Size(r * 1.2f, r * 0.6f))
        }
        3 -> { // shrub
            drawOval(Color(0x33203040), Offset(x - r * 0.9f, y - r * 0.2f), Size(r * 2.2f, r * 1.4f))
            drawCircle(Color(0xFF3B5E4F), r * 0.8f, Offset(x - r * 0.45f, y))
            drawCircle(Color(0xFF486F5C), r * 0.85f, Offset(x + r * 0.4f, y + r * 0.1f))
            drawCircle(Color(0xFF557F69), r * 0.7f, Offset(x, y - r * 0.4f))
            drawCircle(Color(0xFFF4F9FC), r * 0.35f, Offset(x - r * 0.1f, y - r * 0.55f))
        }
        else -> { // pine seen from above: soft shadow, layered needle rings, snow dusting
            drawOval(Color(0x30203040), Offset(x - r * 0.45f, y - r * 0.35f), Size(r * 2.1f, r * 1.9f))
            val rings = listOf(
                Color(0xFF244B41), Color(0xFF2F6052), Color(0xFF3E7864), Color(0xFF54927B),
            )
            for (i in rings.indices) {
                val rr = r * (1f - i * 0.22f)
                drawPath(starPath(x, y, rr, rr * 0.66f, 11, seed + i * 0.35f), rings[i])
            }
            drawCircle(Color(0xFF6BA891), r * 0.12f, Offset(x, y))
            for (i in 0 until 5) {
                val ang = seed * 3f + i * 1.26f
                val d = r * (0.45f + 0.12f * (i % 2))
                drawCircle(Color.White.copy(alpha = 0.8f), r * 0.14f, Offset(x + cos(ang) * d, y + sin(ang) * d))
            }
            drawCircle(Color.White.copy(alpha = 0.85f), r * 0.2f, Offset(x - r * 0.12f, y - r * 0.14f))
        }
    }
}

private fun DrawScope.drawTrack(scroll: Float, len: Float) {
    val cx = CAR_W / 2f
    val top = -900f
    val total = len + 1800f
    val art = sceneArt
    if (art != null) {
        // ballast, wooden sleepers and steel rails from one 66 x 111 dp photo-based tile
        texRect(art.track, cx - 33f, top, 66f, total, 4f, ax = cx - 33f, ay = scroll % 111f)
        return
    }
    // gravel bed with darker edges
    box(Color(0xFF7C8793), cx - 33f, top, 66f, total)
    box(Color(0xFF99A5B0), cx - 30f, top, 60f, total)
    // sleepers: ids stay attached to the ground as the track scrolls
    val n = (scroll / 14f).toInt()
    val off = scroll % 14f
    var y = top - 2f + off
    var k = 0
    while (y < len + 900f) {
        val id = n - k
        val dark = (id * 7 + 3) % 5 == 0
        box(Color(0x33000000), cx - 24f, y + 1.5f, 50f, 4.5f, 1f)
        box(if (dark) Color(0xFF5A4A3B) else Color(0xFF6E5B49), cx - 25f, y, 50f, 4.5f, 1f)
        box(Color(0x22FFFFFF), cx - 25f, y, 50f, 1f)
        y += 14f
        k++
    }
    // steel rails with a bright top edge
    for (rx in listOf(cx - 16f, cx + 12f)) {
        box(Color(0x33000000), rx + 1.5f, top, 4f, total)
        box(Color(0xFF4A5560), rx, top, 4f, total)
        box(Color(0xFFC5CED6), rx + 1.2f, top, 1.2f, total)
    }
}

private fun DrawScope.drawTrain(tier: TrainTier, look: Look, npc: Npc, time: Float, boosting: Boolean) {
    val body = Color(tier.body)
    val accent = Color(tier.accent)
    val cars = look.cars
    sceneCarCount = cars
    drawNose(body, accent, look.plow)
    for (i in 0 until cars) {
        val top = NOSE + i * PITCH
        // skip cars that are off screen (each car draws several layers)
        if (top + CAR_H < npc.camY - 80f || top > npc.camY + npc.viewH + 80f) continue
        val floor: Color
        val plank: Color
        when (i) {
            0 -> { floor = Color(0xFF98A3AD); plank = Color(0xFF8A949E) }
            1 -> { floor = Color(0xFFE3DCCB); plank = Color(0xFFD3CBB8) }
            else -> when ((i - 2) % 4) {
                1 -> { floor = Color(0xFFD9CBB4); plank = Color(0xFFC9B99F) }   // passenger lounge
                2 -> { floor = Color(0xFFB9CDB0); plank = Color(0xFFA6BC9D) }   // greenhouse
                3 -> { floor = Color(0xFFA9B1B9); plank = Color(0xFF99A2AB) }   // workshop
                else -> { floor = Color(0xFFC49A6C); plank = Color(0xFFAF8559) } // cargo hold
            }
        }
        drawCarShell(top, body, accent, floor, plank, metal = i == 0, floorIdx = i)
        if ("RUG" in sceneDecor) drawRug(top)
        when (i) {
            0 -> drawEngineCar(top, look, npc, time, boosting)
            1 -> drawFoodCar(top, look, npc, time)
            else -> drawSeatingCar(top, i, cars)
        }
        if (i >= 2) drawRoofStyle(top, body, accent)  // only the plain seating coaches carry the roof detail
        if (i < cars - 1) drawVestibule(top + CAR_H)
    }
    drawCarDoors(cars, npc)
    drawLeaversInside()
    run {
        val u = density
        for (b in sceneBoarders) {
            if (b.y > NOSE + cars * PITCH) continue   // never draw anyone past the last car
            b.npc?.let { look ->
                drawOval(Color(0x22000000), Offset((b.x - 9f) * u, (b.y + 8f) * u), Size(18f * u, 6f * u))
                drawNpc(look, b.x * u, (b.y + 10f) * u, NPC_TRAIN_H * u, sceneClock + b.bob, sceneClock * 10f + b.bob, 1f, b.facing, 1f)
            }
            if (b.npc != null) continue
            val img = b.img ?: continue
            drawOval(Color(0x22000000), Offset((b.x - 9f) * u, (b.y + 8f) * u), Size(18f * u, 6f * u))
            if (img.height > img.width * 1.6f) {
                // chibi full body: a skinned mesh that really walks
                val bh = 32f * (img.height - 2 * MeshPuppet.PAD) / 322f
                drawChibi(img, b.side, b.x * u, (b.y + 10f) * u, bh * u, sceneClock + b.bob, sceneClock * 10f + b.bob, 1f, b.facing, 1f, spriteXScale)
            } else drawWalkingSprite(img, b.x * u, (b.y + 10f) * u, 22f, 27f, sceneClock * 10f + b.bob, 1f, flip = b.flip)
        }
        sceneBoarders.clear()
    }
    if ("LIGHTS" in sceneDecor || "LANTERNS" in sceneDecor) for (i in 0 until cars) {
        val top = NOSE + i * PITCH
        if (top + CAR_H < npc.camY - 80f || top > npc.camY + npc.viewH + 80f) continue
        if ("LIGHTS" in sceneDecor) drawStringLights(top, time)
        if ("LANTERNS" in sceneDecor) drawLanterns(top, time)
    }
    // Closed roofs slide over the whole train when you zoom right out, and fade away to reveal
    // the interior as you zoom back in (so from far off it reads as a real train seen from above).
    val roofA = ((1f - sceneUserZoom) / 0.4f).coerceIn(0f, 1f)
    if (roofA > 0.01f) {
        drawNoseRoof(body, accent, roofA)
        for (i in 0 until cars) {
            val top = NOSE + i * PITCH
            if (top + CAR_H < npc.camY - 80f || top > npc.camY + npc.viewH + 80f) continue
            drawCarRoof(top, body, accent, i, roofA)
            if (i < cars - 1) box(lerp(body, Color.Black, 0.12f).copy(alpha = roofA), AISLE_X - 14f, top + CAR_H, 28f, GAP, 2f)
        }
    }
}

/** A coach roof seen from above: body panel, shaded eaves, a raised centre ridge, seams and vents.
 *  Drawn at [a] alpha so it can fade in when zoomed out and vanish when zoomed in. */
private fun DrawScope.drawCarRoof(top: Float, body: Color, accent: Color, i: Int, a: Float) {
    val dark = lerp(body, Color.Black, 0.20f)
    val lite = lerp(body, Color.White, 0.14f)
    val ridge = lerp(body, Color.White, 0.26f)
    val roofImg = sceneSprites?.carRoof
    if (roofImg != null && i > 0) {
        val u = density
        squeezedSprites { drawSprite(roofImg, -3f * u, (top - 3f) * u, (CAR_W + 6f) * u, (CAR_H + 6f) * u, tint = lerp(body, Color.White, 0.55f), alpha = a) }
        return
    }
    box(body.copy(alpha = a), 0f, top, CAR_W, CAR_H, 12f)
    // curved roof edges: darker eaves down each long side
    box(dark.copy(alpha = a * 0.9f), 1f, top + 2f, 13f, CAR_H - 4f, 7f)
    box(dark.copy(alpha = a * 0.9f), CAR_W - 14f, top + 2f, 13f, CAR_H - 4f, 7f)
    // raised centre ridge with a soft highlight
    box(ridge.copy(alpha = a), AISLE_X - 20f, top + 4f, 40f, CAR_H - 8f, 10f)
    box(lite.copy(alpha = a * 0.7f), AISLE_X - 3f, top + 8f, 5f, CAR_H - 16f, 2f)
    // transverse roof seams
    var sy = top + 18f
    while (sy < top + CAR_H - 10f) { box(dark.copy(alpha = a * 0.5f), 10f, sy, CAR_W - 20f, 1.4f, 0.6f); sy += 22f }
    // accent band toward the front
    box(accent.copy(alpha = a * 0.85f), 22f, top + 2.5f, CAR_W - 44f, 3f, 1.2f)
    if (i == 0) {
        // engine roof: a chimney and an exhaust vent
        dot(Color(0xFF2B2F36).copy(alpha = a), AISLE_X.toFloat(), top + 26f, 9f)
        dot(Color(0xFF4B525C).copy(alpha = a), AISLE_X.toFloat(), top + 26f, 5f)
        box(dark.copy(alpha = a), AISLE_X - 8f, top + 60f, 16f, 14f, 3f)
    } else {
        for (vy in listOf(top + 30f, top + 62f, top + 94f)) {
            box(dark.copy(alpha = a), AISLE_X - 9f, vy, 18f, 13f, 3f)
            box(lite.copy(alpha = a), AISLE_X - 7f, vy + 2f, 14f, 4f, 2f)
        }
    }
}

