/** The worker busy with [act] right now, if any. */
private fun crewDoing(npc: Npc, act: Act): Npc? =
    if (npc.working && npc.act == act) npc else sceneNpc2?.takeIf { it.working && it.act == act }

/** Seconds since a worker last finished [act] (99 if long ago). */
private fun crewSince(npc: Npc, act: Act): Float {
    var best = if (npc.doneAct == act) npc.sinceDone else 99f
    sceneNpc2?.let { if (it.doneAct == act) best = min(best, it.sinceDone) }
    return best
}

/** How visible a worker is "in bed": fades in when they lie down and out when they get up. */
private fun sleepFade(n: Npc): Float {
    val dur = n.step?.dur ?: 1f
    return min(n.actT / 0.35f, (dur - n.actT) / 0.35f).coerceIn(0f, 1f)
}

private fun carY(car: Int, localY: Float): Float = NOSE + car * PITCH + localY

/** The worker visits every installed station in turn. Positions are car-local, converted by carY. */
private fun buildCycle(heat: Boolean, food: Boolean, bed: Boolean, wagon: Boolean, cars: Int): List<Step> {
    val s = ArrayList<Step>()
    s.add(Step(112f, carY(0, 28f), 1f, 0f, Act.SHOVEL_PICK, 1.0f))
    s.add(Step(88f, carY(0, 34f), -1f, 0f, Act.SHOVEL_DROP, 1.1f))
    s.add(Step(112f, carY(0, 28f), 1f, 0f, Act.SHOVEL_PICK, 1.0f))
    s.add(Step(88f, carY(0, 34f), -1f, 0f, Act.SHOVEL_DROP, 1.1f))
    s.add(Step(112f, carY(0, 94f), 1f, 0f, Act.DRIVE, 2.2f))
    if (heat) s.add(Step(74f, carY(1, 34f), -1f, 0f, Act.TURN_VALVE, 2.4f))
    if (food) {
        s.add(Step(124f, carY(1, 30f), 1f, 0f, Act.COOK, 4.2f))
        s.add(Step(76f, carY(1, 92f), -1f, 0f, Act.EAT, 2.4f))
    }
    if (wagon) {
        s.add(Step(86f, carY(1, 96f), -1f, 0f, Act.CRATE_PICK, 1.0f))
        s.add(Step(104f, carY(1, 94f), 1f, 0f, Act.CRATE_PLACE, 1.1f))
    }
    // check on the devices in every extra car
    for (c in 2 until cars) s.add(Step(AISLE_X, carY(c, 56f), if (c % 2 == 0) -1f else 1f, 0f, Act.TURN_VALVE, 1.3f))
    if (bed) s.add(Step(68f, carY(0, 94f), -1f, 0f, Act.SLEEP, 4.0f))
    return s
}

/** Animation-only state for the worker (not part of the game rules). */
private class Npc {
    var x = AISLE_X
    var y = NOSE + 70f
    var faceDeg = 0f
    var phase = 0f
    var actT = 0f
    /** The last job finished and how long ago (seconds), for little "done" effects. */
    var doneAct: Act? = null
    var sinceDone = 99f
    var camY = 0f
    var zoom = 1f
    var originXpx = 0f      // set while drawing; used to turn taps into train-space positions
    var centerOffDp = 0f
    var cars = 2
    var manualCam = 0f      // camera position while the player scrolls by hand
    var manualLeft = 0f     // seconds left before the camera follows the worker again
    var viewH = 600f // visible height in train-space dp, set from the canvas every frame
    var trainLen = NOSE + 2 * PITCH
    /** Hand scrolling can bring the first or the last car all the way to the middle of the screen. */
    val camLo: Float get() = NOSE + CAR_H / 2f - viewH / 2f
    val camHi: Float get() = max(camLo, trainLen - CAR_H / 2f - viewH / 2f)
    /** Automatic camera: a short train sits in the middle; a long one follows the worker. */
    private val autoLo: Float get() = if (trainLen <= viewH) (trainLen - viewH) / 2f else -60f
    private val autoHi: Float get() = if (trainLen <= viewH) autoLo else trainLen - viewH + 30f
    /** Where the automatic camera would be. The world outside is drawn relative to it, so scrolling by hand
     *  moves the snow and stations together with the train instead of sliding the train past a still world. */
    var camAuto = 0f
    var working = false
    var cycle: List<Step> = emptyList()
    var idx = 0
    var sig = Int.MIN_VALUE
    var startOffset = 0 // lets a second worker begin halfway through the routine
    private val path = ArrayList<Offset>()

    val step: Step? get() = if (cycle.isEmpty()) null else cycle[idx % cycle.size]
    val act: Act get() = if (working) (step?.act ?: Act.WALK) else Act.WALK
    val carIdx: Int get() = max(0, ((y - NOSE) / PITCH).toInt())

    val carrying: Boolean
        get() {
            val st = step ?: return false
            return st.act == Act.CRATE_PLACE && (!working || actT < st.dur * 0.5f)
        }

    val holdingCoal: Boolean
        get() {
            val st = step ?: return false
            return st.act == Act.SHOVEL_DROP && (!working || actT < st.dur * 0.6f)
        }

    fun sync(heat: Boolean, food: Boolean, bed: Boolean, wagon: Boolean, cars: Int) {
        val s = (if (heat) 1 else 0) + (if (food) 2 else 0) + (if (bed) 4 else 0) + (if (wagon) 8 else 0) + cars * 16
        if (s == sig) return
        sig = s
        cycle = buildCycle(heat, food, bed, wagon, cars)
        this.cars = cars
        trainLen = NOSE + cars * PITCH - GAP + 10f
        if (y > trainLen - 20f) y = trainLen - 20f
        // startOffset -1 = begin halfway through the routine, so two workers never move in lockstep
        idx = if (cycle.isEmpty() || startOffset == 0) 0 else (if (startOffset < 0) cycle.size / 2 else startOffset % cycle.size)
        if (startOffset != 0) cycle.getOrNull(idx)?.let { x = it.x; y = it.y }
        plan()
    }

    /** Survivors wander from car to car and stop for a while at different spots. */
    fun syncWander(cars: Int, seed: Int) {
        val s = 1_000_000 + cars * 10 + seed
        if (s == sig) return
        sig = s
        val steps = ArrayList<Step>()
        for (c in 0 until cars) {
            val k = (c * 7 + seed * 13)
            val x = AISLE_X + ((k * 37) % 40 - 20).toFloat()
            val y = carY(c, 34f + (k * 29) % 46)
            steps.add(Step(x, y, if (k % 2 == 0) 1f else -1f, 0.2f, Act.EAT, 2.5f + (k % 4)))
        }
        if (seed % 2 == 1) steps.reverse()
        cycle = steps
        this.cars = cars
        trainLen = NOSE + cars * PITCH - GAP + 10f
        idx = seed % max(1, steps.size)
        cycle.getOrNull(idx)?.let { x = it.x; y = it.y }
        plan()
    }

    private fun plan() {
        path.clear()
        working = false
        actT = 0f
        val t = step ?: return
        if (abs(x - AISLE_X) > 1f) path.add(Offset(AISLE_X, y))
        if (abs(y - t.y) > 1f) path.add(Offset(AISLE_X, t.y))
        path.add(Offset(t.x, t.y))
    }

    private fun turnTo(target: Float, d: Float) {
        var diff = (target - faceDeg) % 360f
        if (diff > 180f) diff -= 360f
        if (diff < -180f) diff += 360f
        faceDeg += diff * min(1f, d * 12f)
    }

    fun update(dt: Float, tempo: Float) {
        val st = step ?: return
        val d = dt * tempo
        if (sinceDone < 99f) sinceDone += dt
        if (!working && path.isNotEmpty()) {
            val tgt = path[0]
            val dx = tgt.x - x
            val dy = tgt.y - y
            val dist = sqrt(dx * dx + dy * dy)
            val stride = 64f * d
            if (dist <= stride) {
                x = tgt.x
                y = tgt.y
                path.removeAt(0)
            } else {
                x += dx / dist * stride
                y += dy / dist * stride
            }
            if (dist > 0.01f) turnTo(atan2(dx, -dy) * 57.29578f, d)
            phase += d * 9f
            if (path.isEmpty()) {
                working = true
                actT = 0f
            }
        } else if (working) {
            turnTo(atan2(st.fx, -st.fy) * 57.29578f, d)
            actT += d
            phase += d * 6f
            if (actT >= st.dur) {
                doneAct = st.act
                sinceDone = 0f
                idx = (idx + 1) % cycle.size
                plan()
            }
        }
        camAuto += ((y - viewH / 2f).coerceIn(autoLo, autoHi) - camAuto) * min(1f, dt * 3f)
        if (manualLeft > 0f) {
            manualLeft -= dt
            camY += (manualCam - camY) * min(1f, dt * 12f)
        } else {
            val target = (y - viewH / 2f).coerceIn(autoLo, autoHi)
            camY += (target - camY) * min(1f, dt * 3f)
        }
    }
}

/** Shared with the UI: where the camera is (in cars) for the mini-map, and a car to jump to. */
class SceneLink {
    /** The player's zoom on top of the automatic fit (buttons or pinch). */
    var zoom by androidx.compose.runtime.mutableFloatStateOf(1f)
    var camCar by androidx.compose.runtime.mutableFloatStateOf(0f)
    var viewCars by androidx.compose.runtime.mutableFloatStateOf(3f)
    var jumpCar = -1
    /** < 1 while a menu shrinks the view: the scene is laid out larger by 1/viewScale and drawn scaled down. */
    var viewScale = 1f
    /** The car just picked on the map; it glows for a moment so it is easy to find. -1 = none. */
    var flashCar by androidx.compose.runtime.mutableIntStateOf(-1)
    var flashLeft = 0f
}

@Composable
fun TrainScene(vm: GameViewModel, modifier: Modifier = Modifier, onDeviceTap: (UpgradeType) -> Unit = {}, link: SceneLink? = null) {
    val npc = remember { Npc() }
    val roster = remember { ArrayList<ScenePax?>() }
    val rosterReady = remember { booleanArrayOf(false) }
    val npc2 = remember { Npc().also { it.startOffset = -1 } }
    val survivors = remember { List(10) { Npc() } }
    val stations = remember { ArrayList<Station>().apply { if (!vm.debugStationAt.isNaN()) add(Station(vm.debugStationAt)) } }
    val halfH = remember { floatArrayOf(300f) }
    val startStop = remember { booleanArrayOf(false) }
    var seenEvolveStart by remember { mutableIntStateOf(vm.evolveSerial) }
    val stopFactor = remember { floatArrayOf(1f) }
    val shelterDwell = remember { floatArrayOf(-1f) }
    var seenStations by remember { mutableIntStateOf(vm.stationSerial) }
    var seenStorms by remember { mutableIntStateOf(vm.stormStationSerial) }
    // supply crate beside the track: [active, y in dp, side, x px, y px]
    val crate = remember { floatArrayOf(0f, 0f, 0f, 0f, 0f) }
    val zoneSeen = remember { intArrayOf(-1) }
    val wolves = remember { ArrayList<Wolf>() }
    var seenWolves by remember { mutableIntStateOf(vm.wolfSerial) }
    // keepsake sparkle: [active, y dp, side, x px, y px]
    val sparkle = remember { floatArrayOf(0f, 0f, 0f, 0f, 0f) }
    var seenSparkles by remember { mutableIntStateOf(vm.sparkleSerial) }
    // train edges and screen width in dp, written while drawing
    val edges = remember { floatArrayOf(100f, 290f, 390f) }
    val wolfImg = ImageBitmap.imageResource(R.drawable.spr_wolf)
    var seenCrates by remember { mutableIntStateOf(vm.crateSerial) }
    var time by remember { mutableFloatStateOf(0f) }
    // start where the last ride left off, so a new session does not always begin in the same region
    var scroll by remember { mutableFloatStateOf((vm.totalDistance % (ZONE_LEN * ZONES.size).toDouble()).toFloat()) }

    LaunchedEffect(Unit) {
        var last = 0L
        var acc = 0f
        while (true) {
            withFrameNanos { now ->
                if (last != 0L) acc += (now - last) / 1e9f
                // Frame-rate cap from Settings: only update and redraw once enough time has passed.
                if (last != 0L && acc >= 1f / vm.fpsCap - 0.002f) {
                    val dt = acc.coerceAtMost(0.05f)
                    acc = 0f
                    val boosting = vm.isBoosting
                    time += dt
                    vm.audio.zoom = link?.zoom ?: 1f   // the ear moves inside the coach as you zoom in
                    val warmNow = vm.regionTemp >= 24
                    // riders keep their own seat: the roster is a list of seats, empty ones are null
                    sceneClock = time
                    syncRoster(roster, vm.passengers, warmNow, if (rosterReady[0]) time else -100f)
                    rosterReady[0] = true
                    sceneRoster = roster
                    // the train begins each session standing at a platform, then pulls away
                    if (!startStop[0] && halfH[0] > 1f) {
                        startStop[0] = true
                        stations.add(Station(halfH[0]))
                    }
                    // after evolving, the new train also pulls out of a station
                    if (seenEvolveStart != vm.evolveSerial && halfH[0] > 1f) {
                        seenEvolveStart = vm.evolveSerial
                        stations.add(Station(halfH[0]))
                    }
                    while (seenStations < vm.stationSerial) { seenStations++; stations.add(Station(if (vm.debugStationAt.isNaN()) -160f else vm.debugStationAt)) }
                    while (seenStorms < vm.stormStationSerial) { seenStorms++; stations.add(Station(-260f, stop = true)) }
                    // Every station: slow down, stand while passengers get off and on, then pull away.
                    // A storm shelter keeps the train waiting longer.
                    var factor = 1f
                    val shelter = stations.firstOrNull { !it.done }
                    if (shelter == null || !shelter.paid) vm.stationTick(false, false, 0.0)
                    if (shelter != null) {
                        val dist = halfH[0] - shelter.y
                        if (!shelter.paid && dist > 0f) {
                            factor = (dist / 170f).coerceIn(0.07f, 1f)
                        } else {
                            if (!shelter.paid) {
                                shelter.paid = true
                                val r = vm.collectStation(shelter = shelter.stop, waiting = shelter.waiting)
                                shelter.off = r[0]; shelter.on = r[1]
                                shelter.readyAt = stationExchange(roster, shelter, r[0], r[1], time, warmNow)
                                if (shelter.stop) shelter.readyAt = max(shelter.readyAt, time + Balance.STATION_STOP_SEC.toFloat())
                            }
                            shelter.dwell += dt
                            val ready = time >= shelter.readyAt
                            if (shelter.departAt < 0f && vm.stationTick(true, ready, dt.toDouble())) shelter.departAt = time
                            factor = if (shelter.departAt < 0f) 0f else ((time - shelter.departAt) / 2.5f).coerceIn(0f, 1f)
                            if (factor >= 1f) { shelter.done = true; vm.stationTick(false, false, 0.0) }
                        }
                    }
                    // slide the camera over to the station while arriving and standing; back once it is behind us
                    val panTarget = if (shelter != null && !shelter.done && (shelter.paid || halfH[0] - shelter.y < 420f)) 1f else 0f
                    sceneStationPan += (panTarget - sceneStationPan) * (1f - kotlin.math.exp(-dt * 1.6f))
                    sceneLeavers.removeAll { time > it.standAt + LEAVE_IN_SEC + PLATFORM_WALK_SEC + 0.5f }
                    vm.setMoveFactor(factor)
                    stopFactor[0] = factor
                    shelterDwell[0] = shelter?.takeIf { it.paid && !it.done }?.dwell ?: -1f
                    // scenery scroll speed grows only slowly (logarithmically) and is capped, so even a very fast train
                    // still shows the landscape and the biomes do not whip past
                    val scenery = (46f + 30f * kotlin.math.ln(1f + vm.travelSpeed.toFloat())).coerceAtMost(185f)
                    val ds = scenery * (if (boosting) 1.35f else 1f) * dt * factor
                    scroll += ds
                    // a new region of the frozen world reaches the train
                    val zoneNow = zoneAt(scroll - halfH[0])
                    if (zoneNow != zoneSeen[0]) { vm.enterRegion(zoneNow, ZONES[zoneNow].name, ZONES[zoneNow].temp); zoneSeen[0] = zoneNow }
                    if (seenCrates < vm.crateSerial) {
                        seenCrates = vm.crateSerial
                        crate[0] = 1f; crate[1] = -70f; crate[2] = if (Math.random() < 0.5) 0f else 1f
                    }
                    // keepsake sparkles scroll past like crates
                    if (seenSparkles < vm.sparkleSerial) {
                        seenSparkles = vm.sparkleSerial
                        sparkle[0] = 1f; sparkle[1] = -60f; sparkle[2] = if (Math.random() < 0.5) 0f else 1f
                    }
                    if (sparkle[0] > 0f) { sparkle[1] += ds; if (sparkle[1] > halfH[0] * 2f + 60f) sparkle[0] = 0f }
                    // wolves: a small pack runs at the train from both sides
                    if (seenWolves < vm.wolfSerial) {
                        seenWolves = vm.wolfSerial
                        val n = (3..5).random()
                        for (k in 0 until n) {
                            val side = k % 2
                            wolves.add(Wolf(if (side == 0) -30f else edges[2] + 30f, halfH[0] * (0.45f + Math.random().toFloat() * 1.1f), side, k * 1.1f))
                        }
                    }
                    if (wolves.isNotEmpty()) {
                        for (wf in wolves) {
                            if (wf.delay > 0f) { wf.delay -= dt; continue }
                            wf.t += dt
                            if (wf.state == 0) {
                                val target = if (wf.side == 0) edges[0] - 8f else edges[1] + 8f
                                val dir = if (wf.side == 0) 1f else -1f
                                wf.x += dir * 38f * dt
                                if ((wf.side == 0 && wf.x >= target) || (wf.side == 1 && wf.x <= target)) { wf.state = 2; vm.wolfReached() }
                            } else if (wf.state == 1) {
                                wf.x += (if (wf.side == 0) -1f else 1f) * 190f * dt
                            }
                            wf.y += ds * 0.4f
                        }
                        wolves.removeAll { it.state == 2 || it.x < -80f || it.x > edges[2] + 80f && it.state == 1 }
                        if (wolves.isEmpty()) vm.endWolves()
                    }
                    if (crate[0] > 0f) {
                        if (vm.event != GameEvent.CRATE) crate[0] = 0f
                        else {
                            crate[1] += ds
                            if (crate[1] > halfH[0] * 2f + 70f) { crate[0] = 0f; vm.missCrate() }
                        }
                    }
                    for (st in stations) {
                        st.y += ds
                    }
                    stations.removeAll { it.y > halfH[0] * 2f + 260f }
                    npc.sync(
                        heat = vm.level(UpgradeType.HEAT) > 0,
                        food = vm.level(UpgradeType.FOOD) > 0,
                        bed = vm.level(UpgradeType.CONDUCTOR) > 0,
                        wagon = vm.level(UpgradeType.WAGON) > 0,
                        cars = carCount(vm),
                    )
                    npc.update(dt, if (boosting) 1.8f else 1f)
                    if (link != null) {
                        if (link.jumpCar >= 0) {
                            val target = NOSE + link.jumpCar * PITCH + CAR_H / 2f - npc.viewH / 2f
                            npc.manualCam = target.coerceIn(npc.camLo, npc.camHi)
                            npc.manualLeft = 6f
                            link.flashCar = link.jumpCar
                            link.flashLeft = 1.8f
                            link.jumpCar = -1
                        }
                        if (link.flashLeft > 0f) {
                            link.flashLeft -= dt
                            if (link.flashLeft <= 0f) link.flashCar = -1
                        }
                        sceneFlashCar = link.flashCar
                        sceneFlash = link.flashLeft
                        val camCar = (npc.camY - NOSE) / PITCH
                        if (kotlin.math.abs(camCar - link.camCar) > 0.02f) link.camCar = camCar
                        val vc = npc.viewH / PITCH
                        if (kotlin.math.abs(vc - link.viewCars) > 0.02f) link.viewCars = vc
                    }
                    val survivorCount = min(vm.level(UpgradeType.SURVIVORS), survivors.size)
                    for (i in 0 until survivorCount) {
                        survivors[i].syncWander(carCount(vm), i)
                        survivors[i].update(dt, 0.8f)
                    }
                    if (vm.permLevel(PermType.CREW) > 0) {
                        npc2.sync(
                            heat = vm.level(UpgradeType.HEAT) > 0,
                            food = vm.level(UpgradeType.FOOD) > 0,
                            bed = vm.level(UpgradeType.CONDUCTOR) > 0,
                            wagon = vm.level(UpgradeType.WAGON) > 0,
                            cars = carCount(vm),
                        )
                        npc2.update(dt, if (boosting) 1.8f else 1f)
                    }
                }
                last = now
            }
        }
    }

    val art = rememberSceneArt()
    val mats = rememberMaterials()
    val sprites = rememberGameSprites()
    val base = TIERS[vm.tierIndex]
    val lv = LIVERIES[vm.liveryIndex.coerceIn(0, LIVERIES.lastIndex)]
    val tier = if (vm.liveryIndex > 0 && vm.liveryUnlocked(vm.liveryIndex)) TrainTier(base.name, lv.body, lv.accent) else base
    Canvas(
        modifier.pointerInput(Unit) {
            // Tap a device on the train to open its upgrade.
            detectTapGestures { pos ->
                val u = density
                if (crate[0] > 0f && kotlin.math.hypot(pos.x - crate[3], pos.y - crate[4]) < 40f * u) {
                    crate[0] = 0f
                    vm.collectCrate()
                    return@detectTapGestures
                }
                if (sparkle[0] > 0f && kotlin.math.hypot(pos.x - sparkle[3], pos.y - sparkle[4]) < 40f * u) {
                    sparkle[0] = 0f
                    vm.collectSparkle()
                    return@detectTapGestures
                }
                wolves.firstOrNull { it.state == 0 && it.delay <= 0f && kotlin.math.hypot(pos.x - it.x * u, pos.y - it.y * u) < 30f * u }?.let {
                    it.state = 1
                    vm.chaseWolf()
                    return@detectTapGestures
                }
                val tx = (pos.x - npc.originXpx) / (u * npc.zoom * TRAIN_SQUEEZE)
                val ty = pos.y / (u * npc.zoom) - (npc.centerOffDp - npc.camY)
                hotspotAt(tx, ty, npc.cars)?.let(onDeviceTap)
            }
        }.pointerInput(Unit) {
            // Drag up or down to look along a long train (the camera follows the worker again after 5 s);
            // pinch with two fingers to zoom in or out.
            awaitEachGesture {
                awaitFirstDown(requireUnconsumed = false)
                npc.manualCam = npc.camY
                var moving = false
                var travel = 0f
                do {
                    val ev = awaitPointerEvent()
                    val fingers = ev.changes.count { it.pressed }
                    val zoomCh = if (fingers >= 2) ev.calculateZoom() else 1f
                    val pan = ev.calculatePan()
                    if (!moving) {
                        travel += kotlin.math.abs(pan.y) + kotlin.math.abs(zoomCh - 1f) * 200f
                        if (travel > viewConfiguration.touchSlop || fingers >= 2) moving = true
                    }
                    if (moving) {
                        if (zoomCh != 1f && link != null) link.zoom = (link.zoom * zoomCh).coerceIn(ZOOM_MIN, ZOOM_MAX)
                        if (pan.y != 0f && npc.camHi > npc.camLo) {
                            npc.manualCam = (npc.manualCam - pan.y / (density * npc.zoom)).coerceIn(npc.camLo, npc.camHi)
                            npc.manualLeft = 5f
                        }
                        ev.changes.forEach { if (it.positionChanged()) it.consume() }
                    }
                } while (ev.changes.any { it.pressed })
            }
        }
    ) {
        val look = Look(
            heat = vm.level(UpgradeType.HEAT),
            food = vm.level(UpgradeType.FOOD),
            coal = vm.level(UpgradeType.COAL),
            booster = vm.level(UpgradeType.BOOSTER),
            conductor = vm.level(UpgradeType.CONDUCTOR),
            plow = vm.level(UpgradeType.PLOW),
            cars = carCount(vm),
            wagon = vm.level(UpgradeType.WAGON),
            lv = IntArray(UpgradeType.values().size) { vm.levels.getOrElse(it) { 0 } },
        )
        halfH[0] = size.height / density / 2f
        sceneArt = art
        sceneMats = mats
        sceneSprites = sprites
        sceneUserZoom = link?.zoom ?: 1f
        sceneViewScale = link?.viewScale ?: 1f
        sceneGfx = vm.gfx
        sceneGolden = vm.meta.golden.toList()
        sceneDecor = vm.meta.decor.toList()
        sceneTier = vm.tierIndex
        scenePassengers = vm.passengers
        sceneCountry = vm.countryIndex
        sceneWarm = vm.regionTemp >= 24
        sceneWalkers = FloatArray(2 + 2 + survivors.size * 2).also { a ->
            a[0] = npc.x; a[1] = npc.y
            val crew = vm.permLevel(PermType.CREW) > 0
            a[2] = if (crew) npc2.x else -999f; a[3] = if (crew) npc2.y else -999f
            val ns = min(vm.level(UpgradeType.SURVIVORS), survivors.size)
            for (k in survivors.indices) { a[4 + k * 2] = if (k < ns) survivors[k].x else -999f; a[5 + k * 2] = if (k < ns) survivors[k].y else -999f }
        }
        shopCocoa = vm.shopIncomeLeft > 0.0
        shopTurbo = vm.shopSpeedLeft > 0.0
        sceneSurvivors = survivors.take(min(vm.level(UpgradeType.SURVIVORS), survivors.size))
        drawScene(npc, if (vm.permLevel(PermType.CREW) > 0) npc2 else null, time, scroll, tier, look, vm.isBoosting, vm.event == GameEvent.AURORA, vm.stormLevel, vm.darkness, stations, vm.gfx >= 1)
        if (crate[0] > 0f) {
            val u = density
            val trainPx = CAR_W * u * npc.zoom * TRAIN_SQUEEZE
            val ox = npc.originXpx
            val cx = if (crate[2] < 0.5f) ox * 0.5f else ox + trainPx + (size.width - ox - trainPx) * 0.5f
            val cy = (crate[1] + (npc.camAuto - npc.camY) * npc.zoom) * u
            crate[3] = cx; crate[4] = cy
            drawSupplyCrate(cx, cy, time, sprites.crate)
        }
        run {
            val u = density
            val trainPx = CAR_W * u * npc.zoom * TRAIN_SQUEEZE
            val ox = npc.originXpx
            edges[0] = ox / u; edges[1] = (ox + trainPx) / u; edges[2] = size.width / u
            if (sparkle[0] > 0f) {
                val cx = if (sparkle[2] < 0.5f) ox * 0.5f else ox + trainPx + (size.width - ox - trainPx) * 0.5f
                val cy = (sparkle[1] + (npc.camAuto - npc.camY) * npc.zoom) * u
                sparkle[3] = cx; sparkle[4] = cy
                drawKeepsakeSparkle(cx, cy, time)
            }
            for (wf in wolves) {
                if (wf.delay > 0f) continue
                val run = kotlin.math.abs(sin(wf.t * 12f)) * 3f * u
                val faceRight = (wf.side == 0) == (wf.state == 0)
                val sz = 44f * u
                withTransform({
                    translate(wf.x * u, wf.y * u - run)
                    if (!faceRight) scale(-1f, 1f, Offset.Zero)
                }) {
                    drawImage(wolfImg, dstOffset = IntOffset((-sz / 2f).toInt(), (-sz * 0.6f).toInt()), dstSize = IntSize(sz.toInt(), (sz * 0.75f).toInt()))
                }
                if (wf.state == 0) {
                    // a little exclamation bubble so they read as "tap me"
                    drawCircle(Color(0xFFFFF6E9), 7f * u, Offset(wf.x * u, wf.y * u - 30f * u))
                    drawCircle(Color(0xFF6B4A3A), 7f * u, Offset(wf.x * u, wf.y * u - 30f * u), style = Stroke(1.5f * u))
                    drawLine(Color(0xFFE5484D), Offset(wf.x * u, wf.y * u - 34f * u), Offset(wf.x * u, wf.y * u - 29f * u), 2f * u, StrokeCap.Round)
                    drawCircle(Color(0xFFE5484D), 1.1f * u, Offset(wf.x * u, wf.y * u - 26.5f * u))
                }
            }
        }
    }
}

// ---------------------------------------------------------------------------------------------
// Drawing helpers (everything takes dp and converts with the screen density)
// ---------------------------------------------------------------------------------------------
private fun DrawScope.box(color: Color, x: Float, y: Float, w: Float, h: Float, r: Float = 0f) {
    val u = density
    if (r > 0f) {
        drawRoundRect(color, Offset(x * u, y * u), Size(w * u, h * u), CornerRadius(r * u, r * u))
    } else {
        drawRect(color, Offset(x * u, y * u), Size(w * u, h * u))
    }
}

private fun DrawScope.dot(color: Color, x: Float, y: Float, r: Float) {
    drawCircle(color, r * density, Offset(x * density, y * density))
}

private fun DrawScope.line(color: Color, x1: Float, y1: Float, x2: Float, y2: Float, w: Float) {
    val u = density
    drawLine(color, Offset(x1 * u, y1 * u), Offset(x2 * u, y2 * u), w * u)
}

/** Dashed outline that marks an empty slot where an upgrade will be installed. */
private fun DrawScope.slot(x: Float, y: Float, w: Float, h: Float) {
    val u = density
    drawRoundRect(
        Color(0x668A949E),
        Offset(x * u, y * u),
        Size(w * u, h * u),
        CornerRadius(6f * u, 6f * u),
        style = Stroke(width = 2f * u, pathEffect = PathEffect.dashPathEffect(floatArrayOf(8f * u, 6f * u), 0f)),
    )
}

private fun DrawScope.drawScene(
    npc: Npc, npc2: Npc?, time: Float, scroll: Float, tier: TrainTier, look: Look,
    boosting: Boolean, aurora: Boolean, storm: Float, dark: Float, stations: List<Station>, fx: Boolean,
) {
    sceneNpc2 = npc2
    sceneMainNpc = npc
    val u = density
    val w = size.width
    val h = size.height
    val z = (w * sceneViewScale / u * 0.50f / CAR_W).coerceIn(0.8f, 1.5f) * sceneUserZoom
    npc.viewH = h / u / z
    npc.zoom = z
    fxOn = fx
    fxDark = dark
    sceneStorm = storm
    val trainPx = CAR_W * u * z * TRAIN_SQUEEZE
    // at a station the train slides right so the platform and the station building get the room
    val originX = (w - trainPx) / 2f + sceneStationPan * w * 0.21f
    val centerOff = 0f
    npc.originXpx = originX
    // how far the player has scrolled away from the automatic camera (dp on screen)
    val worldDp = (npc.camAuto - npc.camY) * z
    sceneStationNear = stations.any { kotlin.math.abs(it.y + worldDp - h / u / 2f) < ST_LEN }
    npc.centerOffDp = centerOff
    val groundKey = scroll + worldDp - h / (u * 2f)
    val snowAmt = snowAt(groundKey)
    sceneSnow = snowAmt
