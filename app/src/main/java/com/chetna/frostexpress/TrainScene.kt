        dot(Color(0xFFF28C5A), 136.5f, top + 29f, 1.3f)
        dot(Color(0xFF8FCB7A), 139.6f, top + 30.2f, 1.1f)
        val sa = if (cooking) npc.phase * 2f else 0f
        line(Color(0xFF8B5E3C), 138f, top + 30f, 138f + 7f * cos(sa), top + 30f + 7f * sin(sa), 1.6f)
